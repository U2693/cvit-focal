    pop_ab(); a.rsr()
    a.label("ep_power")
    incz(); a.jsr_abs("eval_power")
    a.jsr_abs("fp_to_i16").sta_d("V_PEXP")
    pop_ab(); a.sta_d("fp_fop").stb_d("fp_fop+2")
    setw("V_SIGN", 0)
    a.lda_d("V_PEXP").bp("ep_pos")
    a.lda_i(1).sta_d("V_SIGN")
    a.lda_d("V_PEXP"); neg_a(); a.sta_d("V_PEXP")
    a.label("ep_pos")
    a.lda_i(0x400F).sta_d("V_BEST")
    a.lda_i(0x4240).sta_d("V_BESTP")
    a.label("ep_loop")
    a.lda_d("V_PEXP").bz("ep_fin")
    a.ldb_i(0xFFFF).aab().stb_d("V_PEXP")
    a.lda_d("V_BEST").ldb_d("V_BESTP")
    a.jsr_abs("fp_clear").jsr_abs("fp_mul").jsr_abs("fp_check")
    a.sta_d("V_BEST").stb_d("V_BESTP")
    a.jmp("ep_loop")
    a.label("ep_fin")
    a.lda_d("V_SIGN").bz("ep_ld")
    a.lda_d("V_BEST").ldb_d("V_BESTP")
    a.sta_d("fp_fop").stb_d("fp_fop+2")
    a.lda_i(0x400F).ldb_i(0x4240)
    a.jsr_abs("fp_clear").jsr_abs("fp_div").jsr_abs("fp_check")
    a.rsr()
    a.label("ep_ld")
    a.lda_d("V_BEST").ldb_d("V_BESTP")
    a.rsr()

    a.label("eval_term")
    a.jsr_abs("eval_power")
    a.label("et_loop")
    push_ab()                                   # the accumulator must survive the peek
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(ord("*")).beq("et_mul")
    a.cmp_al(ord("/")).beq("et_div")
    pop_ab(); a.rsr()
    a.label("et_mul")
    incz(); a.jsr_abs("eval_power")
    a.sta_d("fp_fop").stb_d("fp_fop+2")
    pop_ab(); a.jsr_abs("fp_clear").jsr_abs("fp_mul").jsr_abs("fp_check")
    a.jmp("et_loop")
    a.label("et_div")
    incz(); a.jsr_abs("eval_power")
    a.sta_d("fp_fop").stb_d("fp_fop+2")
    pop_ab(); a.jsr_abs("fp_clear").jsr_abs("fp_div").jsr_abs("fp_check")
    a.jmp("et_loop")

    a.label("eval_expr")
    a.jsr_abs("eval_term")
    a.label("ee_loop")
    push_ab()
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(ord("+")).beq("ee_add")
    a.cmp_al(ord("-")).beq("ee_sub")
    pop_ab(); a.rsr()
    a.label("ee_add")
    incz(); a.jsr_abs("eval_term")
    a.sta_d("fp_fop").stb_d("fp_fop+2")
    pop_ab(); a.jsr_abs("fp_clear").jsr_abs("fp_add").jsr_abs("fp_check")
    a.jmp("ee_loop")
    a.label("ee_sub")
    incz(); a.jsr_abs("eval_term")
    a.sta_d("fp_fop").stb_d("fp_fop+2")
    pop_ab(); a.jsr_abs("fp_clear").jsr_abs("fp_sub").jsr_abs("fp_check")
    a.jmp("ee_loop")

    # ------------------------------------------------------------ program store (64-byte slots: key, text, CR)
    a.label("clear_slots")
    a.lda_i("SLOTS").xfr("A", "Y")
    a.label("cs_loop")
    a.lda_i(0).sta_x("Y")
    for _ in range(4):
        a.inr("Y", 16)
    a.xfr("Y", "A").cmp_ax(SLOTS_END).blo("cs_loop").rsr()

    a.label("clear_all")
    a.jsr_abs("clear_slots")
    a.lda_i("VARS").xfr("A", "Y")
    a.label("ca_loop")
    a.lda_i(0).sta_x("Y", "+")
    a.xfr("Y", "A").cmp_ax(VARS + 104).blo("ca_loop")
    a.lda_i(0).sta_d("V_PCNT").rsr()

    # scan_key: A = address of slot whose key == V_MK, or 0
    a.label("scan_key")
    a.lda_i("SLOTS").xfr("A", "Y")
    a.label("sk_loop")
    a.lda_x("Y").ldb_d("V_MK").sab().bnz("sk_next")
    a.xfr("Y", "A")
    tst_a()
    a.rsr()
    a.label("sk_next")
    for _ in range(4):
        a.inr("Y", 16)
    a.xfr("Y", "A").cmp_ax(SLOTS_END).blo("sk_loop")
    a.lda_i(0).rsr()

    # find_ge: A = slot with the smallest key >= V_KEY (0 if none)
    a.label("find_ge")
    setw("V_BEST", 0xFFFF); setw("V_BESTP", 0)
    a.lda_i("SLOTS").xfr("A", "Y")
    a.label("fg_loop")
    a.lda_x("Y").bz("fg_next")
    a.ldb_d("V_KEY").sab().bnc("fg_next")
    a.lda_x("Y").ldb_d("V_BEST").sab().bl("fg_next")
    a.lda_x("Y").sta_d("V_BEST").xfr("Y", "A").sta_d("V_BESTP")
    a.label("fg_next")
    for _ in range(4):
        a.inr("Y", 16)
    a.xfr("Y", "A").cmp_ax(SLOTS_END).blo("fg_loop")
    a.lda_d("V_BESTP").rsr()

    # store_line: Z at line number digits
    a.label("store_line")
    a.jsr_abs("parse_lineno")
    a.sta_d("V_NEWKEY").sta_d("V_MK")
    tst_a()
    a.bz("err_syntax")
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(0x0D).bne("sl_store")
    a.jsr_abs("scan_key").bz("sl_ret")             # delete
    a.xfr("A", "Y").lda_i(0).sta_x("Y")
    a.label("sl_ret").rsr()
    a.label("sl_store")
    a.jsr_abs("scan_key").bnz("sl_have")
    setw("V_MK", 0)
    a.jsr_abs("scan_key").bz("err_full")
    a.label("sl_have")
    a.xfr("A", "Y").lda_d("V_NEWKEY").sta_x("Y", "+")
    a.label("sl_copy")
    nextch()
    a.stab_x("Y", "+")
    a.cmp_al(0x0D).bne("sl_copy")
    a.rsr()

    # ------------------------------------------------------------ running
    # run_program: run lines with V_KEY <= key <= V_HI starting at the first line >= V_KEY
    a.label("run_program")
    a.label("rp_loop")
    a.lda_d("V_KEY").jsr_abs("find_ge").bz("rp_done")
    a.sta_d("V_PTR").xfr("A", "Y").lda_x("Y").sta_d("V_LINEKEY")
    a.lda_d("V_HI").ldb_d("V_LINEKEY").sab().bnc("rp_done")
    a.lda_d("V_PTR").ldb_i(2).aab().xfr("B", "Z")
    a.jsr_abs("exec_line")
    a.lda_d("V_QUIT").bnz("rp_done")
    a.lda_d("V_RET").bz("rp_noret")
    setw("V_RET", 0); setw("V_STOP", 0)
    a.rsr()
    a.label("rp_noret")
    a.lda_d("V_JUMP").bz("rp_seq")
    a.sta_d("V_KEY")
    setw("V_JUMP", 0); setw("V_STOP", 0)
    a.jmp("rp_loop")
    a.label("rp_seq")
    a.lda_d("V_LINEKEY").ina().sta_d("V_KEY").jmp("rp_loop")
    a.label("rp_done").rsr()

    # exec_line: execute statements at Z until CR (or a stop flag)
    a.label("exec_line")
    a.label("el_loop")
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(0x0D).bne("el_1")
    a.rsr()
    a.label("el_1")
    a.cmp_al(ord(";")).bne("el_cmd")
    incz()
    a.jmp("el_loop")
    a.label("el_cmd")
    nextch()
    a.jsr_abs("upcase").stab_d("V_CMD")
    # Keep the second letter so SET and SAVE can coexist while commands remain
    # first-letter abbreviated.
    peek(); a.jsr_abs("upcase").stab_d("V_SUB")
    a.jsr_abs("skip_word_tail")
    handlers = {"T": "h_type", "S": "h_set_or_save", "A": "h_ask", "I": "h_if", "G": "h_go", "D": "h_do",
                "F": "h_for", "R": "h_return", "Q": "h_quit", "C": "h_comment", "W": "h_write",
                "E": "h_erase", "L": "h_load"}
    for ch in COMMANDS:
        nxt = f"el_n_{ch}"
        a.ldab_d("V_CMD").cmp_al(ord(ch)).bne(nxt)
        a.jsr_abs(handlers[ch]).jmp("el_after")
        a.label(nxt)
    a.jmp_abs("err_syntax")
    a.label("el_after")
    a.lda_d("V_STOP").bz("el_loop")
    a.rsr()

    # ------------------------------------------------------------ statements
    a.label("h_comment").jsr_abs("skip_eol").rsr()
    a.label("h_return")
    setw("V_RET", 1); setw("V_STOP", 1); a.rsr()
    a.label("h_quit")
    setw("V_QUIT", 1); setw("V_STOP", 1); a.rsr()
    a.label("h_erase").jsr_abs("clear_slots").jsr_abs("skip_eol").rsr()

    a.label("h_type")
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(0x0D).bne("ht_1")
    a.rsr()
    a.label("ht_1")
    a.cmp_al(ord(";")).bne("ht_2")
    a.rsr()
    a.label("ht_2")
    a.cmp_al(ord(",")).bne("ht_3")
    incz(); a.jmp("h_type")
    a.label("ht_3")
    a.cmp_al(0x22).bne("ht_4")
    incz(); a.jsr_abs("print_str_z").jmp("h_type")
    a.label("ht_4")
    a.cmp_al(ord("!")).bne("ht_5")
    incz(); a.jsr_abs("crlf").jmp("h_type")
    a.label("ht_5")
    a.cmp_al(ord("#")).bne("ht_6")
    incz(); a.ldab_i(0x0D).jsr_abs("putc").jmp("h_type")
    a.label("ht_6")
    a.cmp_al(ord("%")).bne("ht_expr")
    incz()
    a.label("ht_fmt")
    peek()
    a.cmp_al(ord(".")).beq("ht_fmt_skip")
    not_digit("h_type")
    a.label("ht_fmt_skip")
    incz(); a.jmp("ht_fmt")
    a.label("ht_expr")
    a.jsr_abs("eval_expr")
    push_ab()
    a.xfr("Z", "A").sta_d("V_SVZ")
    pop_ab()
    a.jsr_abs("fp_print")
    a.lda_d("V_SVZ").xfr("A", "Z")
    a.jmp("h_type")

    a.label("h_set_or_save")
    a.ldab_d("V_SUB").cmp_al(ord("A")).beq("h_save")
    a.label("h_set")
    a.jsr_abs("skipsp"); nextch(); a.jsr_abs("upcase").jsr_abs("var_ref")
    a.xfr("Y", "A"); push_a()
    a.jsr_abs("skipsp"); nextch()
    a.cmp_al(ord("=")).bne("err_syntax")
    a.jsr_abs("eval_expr")
    a.sta_d("V_PBASE").stb_d("V_PEXP")
    pop_a(); a.xfr("A", "Y")
    a.lda_d("V_PBASE").sta_x("Y")
    a.ldb_d("V_PEXP").stb_x("Y", disp=2)
    a.rsr()

    a.label("h_ask")
    setw("V_STR", 0)
    a.label("ha_loop")
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(0x0D).bne("ha_1")
    a.rsr()
    a.label("ha_1")
    a.cmp_al(ord(";")).bne("ha_2")
    a.rsr()
    a.label("ha_2")
    a.cmp_al(ord(",")).bne("ha_3")
    incz(); a.jmp("ha_loop")
    a.label("ha_3")
    a.cmp_al(0x22).bne("ha_var")
    incz(); a.jsr_abs("print_str_z"); setw("V_STR", 1); a.jmp("ha_loop")
    a.label("ha_var")
    nextch(); a.jsr_abs("upcase").jsr_abs("var_ref")
    a.xfr("Y", "A"); push_a()
    a.lda_d("V_STR").bnz("ha_noprompt")
    a.ldab_i(ord(":")).jsr_abs("putc")
    a.label("ha_noprompt")
    setw("V_STR", 0)
    a.lda_i("INBUF").xfr("A", "Y").jsr_abs("read_line")
    a.xfr("Z", "A"); push_a()
    a.lda_i("INBUF").xfr("A", "Z").jsr_abs("eval_expr")
    a.sta_d("V_PBASE").stb_d("V_PEXP")
    pop_a(); a.xfr("A", "Z")
    pop_a(); a.xfr("A", "Y")
    a.lda_d("V_PBASE").sta_x("Y")
    a.ldb_d("V_PEXP").stb_x("Y", disp=2)
    a.jmp("ha_loop")

    a.label("h_go")
    a.jsr_abs("skipsp")
    peek()
    not_digit("go_none")
    a.jsr_abs("parse_lineno").jmp("go_set")
    a.label("go_none").lda_i(1)
    a.label("go_set").sta_d("V_JUMP")
    setw("V_STOP", 1)
    a.rsr()

    a.label("h_if")
    a.jsr_abs("skipsp"); nextch()
    a.cmp_al(ord("(")).bne("err_syntax")
    a.jsr_abs("eval_expr"); push_ab()
    a.jsr_abs("skipsp"); nextch()
    a.cmp_al(ord(")")).bne("err_syntax")
    for v in ("V_L1", "V_L2", "V_L3"):
        setw(v, 0)
    for i, v in enumerate(("V_L1", "V_L2", "V_L3")):
        a.jsr_abs("skipsp")
        peek()
        not_digit("if_choose")
        a.jsr_abs("parse_lineno").sta_d(v)
        a.jsr_abs("skipsp")
        peek()
        a.cmp_al(ord(",")).bne("if_choose")
        incz()
    a.label("if_choose")
    pop_ab()
    tst_a()
    a.bnz("if_nz")
    tst_b()
    a.bz("if_zero")
    a.label("if_nz")
    tst_a()
    a.bm("if_neg")
    a.lda_d("V_L3").jmp("if_go")
    a.label("if_neg").lda_d("V_L1").jmp("if_go")
    a.label("if_zero").lda_d("V_L2")
    a.label("if_go")
    a.bz("if_none")
    a.sta_d("V_JUMP")
    setw("V_STOP", 1)
    a.label("if_none").rsr()

    a.label("h_do")
    a.jsr_abs("skipsp").jsr_abs("parse_lineno")
    a.sta_d("V_LO")
    a.lda_d("V_HASDOT").bz("do_group")
    a.lda_d("V_LO").sta_d("V_HI2").jmp("do_go")
    a.label("do_group")
    a.lda_d("V_LO").ldb_i(99).aab().stb_d("V_HI2")
    a.label("do_go")
    a.xfr("Z", "A"); push_a()
    for v in ("V_KEY", "V_LINEKEY", "V_HI"):
        a.lda_d(v); push_a()
    a.lda_d("V_LO").sta_d("V_KEY").lda_d("V_HI2").sta_d("V_HI")
    a.jsr_abs("run_program")
    for v in ("V_HI", "V_LINEKEY", "V_KEY"):
        pop_a(); a.sta_d(v)
    pop_a(); a.xfr("A", "Z")
    a.rsr()

    # FOR v=a[,step],end[;body...]   frame: S+0..3 end, +4..7 step, +8 var addr, +10 body Z
    a.label("h_for")
    a.xfr("S", "A").ldb_i(0xFFF4).aab().xfr("B", "S")
    a.jsr_abs("skipsp"); nextch(); a.jsr_abs("upcase").jsr_abs("var_ref")
    a.xfr("Y", "A").sta_x("S", disp=8)
    a.jsr_abs("skipsp"); nextch()
    a.cmp_al(ord("=")).bne("err_syntax")
    a.jsr_abs("eval_expr")
    a.sta_d("V_PBASE").stb_d("V_PEXP")
    a.lda_x("S", disp=8).xfr("A", "Y")
    a.lda_d("V_PBASE").sta_x("Y")
    a.ldb_d("V_PEXP").stb_x("Y", disp=2)
    a.jsr_abs("skipsp"); nextch()
    a.cmp_al(ord(",")).bne("err_syntax")
    a.jsr_abs("eval_expr").sta_x("S", disp=0).stb_x("S", disp=2)
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(ord(",")).bne("for_two")
    incz()
    a.lda_x("S", disp=0).sta_x("S", disp=4)
    a.lda_x("S", disp=2).sta_x("S", disp=6)
    a.jsr_abs("eval_expr").sta_x("S", disp=0).stb_x("S", disp=2)
    a.jmp("for_body")
    a.label("for_two")
    a.lda_i(0x400F).sta_x("S", disp=4)
    a.lda_i(0x4240).sta_x("S", disp=6)
    a.label("for_body")
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(ord(";")).bne("for_z")
    incz()
    a.label("for_z").xfr("Z", "A").sta_x("S", disp=10)
    a.label("fl_top")
    a.lda_x("S", disp=0).sta_d("fp_fop")
    a.lda_x("S", disp=2).sta_d("fp_fop+2")
    a.lda_x("S", disp=8).xfr("A", "Y").lda_x("Y").ldb_x("Y", disp=2)
    a.jsr_abs("fp_cmp")
    a.sta_d("V_T")
    a.lda_x("S", disp=4).sta_d("V_ACC").lda_d("V_ACC")
    a.bm("fl_neg")
    a.lda_d("V_T").cmp_ax(1).beq("fl_exit").jmp("fl_body")
    a.label("fl_neg")
    a.lda_d("V_T").cmp_ax(0xFFFF).beq("fl_exit")
    a.label("fl_body")
    a.lda_x("S", disp=10).xfr("A", "Z")
    a.jsr_abs("exec_line")
    a.lda_d("V_STOP").bnz("fl_exit")
    a.lda_x("S", disp=4).sta_d("fp_fop")
    a.lda_x("S", disp=6).sta_d("fp_fop+2")
    a.lda_x("S", disp=8).xfr("A", "Y").lda_x("Y").ldb_x("Y", disp=2)
    a.jsr_abs("fp_clear").jsr_abs("fp_add").jsr_abs("fp_check")
    a.sta_d("V_PBASE").stb_d("V_PEXP")
    a.lda_x("S", disp=8).xfr("A", "Y")
    a.lda_d("V_PBASE").sta_x("Y")
    a.ldb_d("V_PEXP").stb_x("Y", disp=2)
    a.jmp("fl_top")
    a.label("fl_exit")
    a.jsr_abs("skip_eol")
    a.xfr("S", "A").ldb_i(12).aab().xfr("B", "S")
    a.rsr()

    # LOAD/SAVE use emulator-assisted cvit file services.  The service reads
    # the complete command line from BX and transfers numbered source lines
    # directly to/from the fixed line-slot area.
    a.label("h_load")
    a.lda_i("LINEBUF").xfr("A", "B").svc(0x57).jsr_abs("skip_eol").rsr()
    a.label("h_save")
    a.lda_i("LINEBUF").xfr("A", "B").svc(0x58).jsr_abs("skip_eol").rsr()

    # WRITE [group|line]: list all, one group, or one exact line.
    a.label("h_write")
    a.jsr_abs("skipsp"); peek()
    not_digit("hw_all")
    a.jsr_abs("parse_lineno").sta_d("V_KEY").sta_d("V_HI2")
    a.lda_d("V_HASDOT").bnz("hw_start")
    a.lda_d("V_HI2").ldb_i(99).aab().stb_d("V_HI2").jmp("hw_start")
    a.label("hw_all")
    setw("V_KEY", 1); setw("V_HI2", 0xFFFF)
    a.label("hw_start")
    a.xfr("Z", "A"); push_a()
    a.label("hw_loop")
    a.lda_d("V_KEY").jsr_abs("find_ge").bz("hw_done")
    a.sta_d("V_PTR").xfr("A", "Y").lda_x("Y").sta_d("V_LINEKEY")
    a.lda_d("V_HI2").ldb_d("V_LINEKEY").sab().bnc("hw_done")
    a.lda_i(100).xfr("A", "Y").lda_d("V_LINEKEY").divu("Y", "A")
    push_a()
    a.xfr("B", "A").jsr_abs("print_number").ldab_i(ord(".")).jsr_abs("putc")
    pop_a(); a.jsr_abs("print_2digit")
    a.ldab_i(0x20).jsr_abs("putc")
    a.lda_d("V_PTR").ldb_i(2).aab().xfr("B", "Z")
    a.label("hw_text")
    nextch()
    a.cmp_al(0x0D).beq("hw_eol")
    a.jsr_abs("putc").jmp("hw_text")
    a.label("hw_eol")
    a.jsr_abs("crlf")
    a.lda_d("V_LINEKEY").ina().sta_d("V_KEY").jmp("hw_loop")
    a.label("hw_done")
    pop_a(); a.xfr("A", "Z").jsr_abs("skip_eol").rsr()

    emit_float_routines(a)

    # ------------------------------------------------------------ data
    for name, text in strings.items():
        a.label(name).asciz(text)

    code = a.bytes()
    hdr = b"CV" + LOAD.to_bytes(2, "big") * 2 + len(code).to_bytes(2, "big") + b"\x01"
    assert a.syms["V_POOL"] + POOL_MAX * 8 <= SLOTS, "variable pool overruns program slots"
    assert LOAD + len(hdr + code) <= LINEBUF, "FOCAL code overruns line buffers"
    return hdr + code, a


