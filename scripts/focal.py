"""FOCAL for cvit: builds the SYSTEM/FOCAL executable (CV header + code).

A small FOCAL-69 flavoured interpreter with 16-bit signed integers.  See docs/focal.md.

Register conventions: Z = text pointer, A/B = scratch + results (expressions return in A),
Y = scratch/pointer.  RT (X) is the JSR link register and must never be used for data.
Values and DO/FOR frames live on the hardware stack (S).
"""
from cpu6asm import Asm

LOAD = 0x5000
LINEBUF, INBUF, VARS = 0x7000, 0x7060, 0x70C0
SLOTS, SLOTS_END, SLOT_SIZE = 0x8000, 0xA000, 64
SCALARS = ["V_MAINSP", "V_RETADDR", "V_SAVEDSP", "V_KEY", "V_LINEKEY", "V_HI", "V_LO", "V_HI2",
           "V_PTR", "V_JUMP", "V_RET", "V_QUIT", "V_STOP", "V_T", "V_ACC", "V_BEST", "V_BESTP",
           "V_MK", "V_NEWKEY", "V_CMD", "V_LEN", "V_HASDOT", "V_L1", "V_L2", "V_L3", "V_SIGN",
           "V_CNT", "V_STR", "V_KEYT", "V_CH", "V_Q"]
COMMANDS = "TSAIGDFRQCWE"


def build_focal():
    a = Asm(LOAD).vars_at(0x7100)
    for n in SCALARS:
        a.var(n)
    for n, v in (("LINEBUF", LINEBUF), ("INBUF", INBUF), ("VARS", VARS), ("SLOTS", SLOTS)):
        a.equ(n, v)

    strings = {}

    def S(name, text):
        strings[name] = text

    S("s_banner", "\r\nCVIT FOCAL V0.1\r\n")
    S("s_prompt", "*")
    S("s_syntax", "\r\n?SYNTAX\r\n")
    S("s_div0", "\r\n?DIV0\r\n")
    S("s_full", "\r\n?FULL\r\n")

    push_a = lambda: a.sta_x("S", "-")
    pop_a = lambda: a.lda_x("S", "+")
    push_b = lambda: a.stb_x("S", "-")
    pop_b = lambda: a.ldb_x("S", "+")
    incz = lambda: a.inr("Z")
    peek = lambda: a.ldab_x("Z")
    nextch = lambda: a.ldab_x("Z", "+")
    tst_a = lambda: a.sta_d("V_T").lda_d("V_T")
    tst_b = lambda: a.stb_d("V_T").ldb_d("V_T")
    neg_a = lambda: a.xfr("A", "B").lda_i(0).sab().xfr("B", "A")
    setw = lambda name, v: a.lda_i(v).sta_d(name)

    def not_digit(l):
        a.cmp_al(0x30).blo(l)
        a.cmp_al(0x3A).bhs(l)

    def puts(label):
        a.lda_label(label).xaz().ldbb_i(2).svc(0x40)

    # ------------------------------------------------------------ startup / main loop
    a.label("start")
    a.xfr("X", "A").sta_d("V_RETADDR")
    a.xfr("S", "A").sta_d("V_SAVEDSP")
    a.jsr_abs("clear_all")
    puts("s_banner")
    a.xfr("S", "A").sta_d("V_MAINSP")

    a.label("main_loop")
    a.lda_d("V_MAINSP").xfr("A", "S")
    for v in ("V_JUMP", "V_RET", "V_STOP", "V_QUIT"):
        setw(v, 0)
    puts("s_prompt")
    a.lda_i("LINEBUF").xfr("A", "Y").jsr_abs("read_line")
    a.lda_i("LINEBUF").xfr("A", "Z")
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(0x0D).beq("main_loop")
    not_digit("direct")
    a.jsr_abs("store_line").jmp("main_loop")
    a.label("direct")
    a.jsr_abs("exec_line")
    a.lda_d("V_QUIT").bnz("do_exit")
    a.lda_d("V_JUMP").bz("main_loop")
    a.sta_d("V_KEY")
    setw("V_JUMP", 0); setw("V_STOP", 0); setw("V_HI", 0xFFFF)
    a.jsr_abs("run_program")
    a.lda_d("V_QUIT").bnz("do_exit")
    a.jmp("main_loop")

    a.label("do_exit")
    a.lda_d("V_SAVEDSP").xfr("A", "S")
    a.lda_d("V_RETADDR").xfr("A", "X")
    a.rsr()

    # ------------------------------------------------------------ errors
    for name, msg in (("err_syntax", "s_syntax"), ("err_div0", "s_div0"), ("err_full", "s_full")):
        a.label(name)
        puts(msg)
        a.jmp_abs("main_loop")

    # ------------------------------------------------------------ console
    a.label("putc").ldbb_i(1).svc(0x40).rsr()
    a.label("crlf").ldab_i(0x0D).jsr_abs("putc").ldab_i(0x0A).jsr_abs("putc").rsr()

    # read_line: Y = buffer; reads up to 60 chars (backspace edits), CR-terminated.
    a.label("read_line")
    setw("V_LEN", 0)
    a.label("rl_loop")
    a.ldbb_i(3).svc(0x40)
    a.cmp_al(0x0D).bne("rl_notcr")
    a.stab_x("Y", "+").jsr_abs("crlf").rsr()
    a.label("rl_notcr")
    a.cmp_al(0x08).beq("rl_bs")
    a.cmp_al(0x7F).beq("rl_bs")
    a.cmp_al(0x20).blo("rl_loop")
    a.stab_d("V_CH")
    a.lda_d("V_LEN").cmp_ax(60).bhs("rl_loop")
    a.ina().sta_d("V_LEN")
    a.ldab_d("V_CH").stab_x("Y", "+").jsr_abs("putc").jmp("rl_loop")
    a.label("rl_bs")
    a.lda_d("V_LEN").bz("rl_loop")
    a.ldb_i(0xFFFF).aab().stb_d("V_LEN")
    a.dcr("Y")
    a.ldab_i(8).jsr_abs("putc").ldab_i(0x20).jsr_abs("putc").ldab_i(8).jsr_abs("putc")
    a.jmp("rl_loop")

    # print_number: A = signed value
    a.label("print_number")
    tst_a()
    a.bp("pn_pos")
    push_a(); a.ldab_i(ord("-")).jsr_abs("putc"); pop_a(); neg_a()
    a.label("pn_pos")
    a.xfr("A", "B")
    setw("V_CNT", 0)
    a.lda_i(10).xfr("A", "Y").xfr("B", "A")
    a.label("pn_div")
    a.divu("Y", "A")                       # A = remainder, B = quotient
    push_a()
    a.lda_d("V_CNT").ina().sta_d("V_CNT")
    tst_b()
    a.bz("pn_out")
    a.xfr("B", "A").jmp("pn_div")
    a.label("pn_out")
    pop_a()
    a.ldb_i(0x30).aab().xfr("B", "A").jsr_abs("putc")
    a.lda_d("V_CNT").ldb_i(0xFFFF).aab().stb_d("V_CNT")
    a.bnz("pn_out")
    a.rsr()

    # print_2digit: A = 0..99
    a.label("print_2digit")
    a.xfr("A", "B").lda_i(10).xfr("A", "Y").xfr("B", "A").divu("Y", "A")
    push_a()
    a.xfr("B", "A").ldb_i(0x30).aab().xfr("B", "A").jsr_abs("putc")
    pop_a()
    a.ldb_i(0x30).aab().xfr("B", "A").jsr_abs("putc")
    a.rsr()

    # ------------------------------------------------------------ text helpers
    a.label("skipsp")
    peek()
    a.cmp_al(0x20).bne("ss_ret")
    incz()
    a.jmp("skipsp")
    a.label("ss_ret").rsr()

    a.label("skip_eol")
    peek()
    a.cmp_al(0x0D).beq("se_ret")
    incz()
    a.jmp("skip_eol")
    a.label("se_ret").rsr()

    a.label("upcase")
    a.cmp_al(0x61).blo("up_ret")
    a.cmp_al(0x7B).bhs("up_ret")
    a.ldbb_i(0x20).sabb().xfrb_bl_al()
    a.label("up_ret").rsr()

    a.label("skip_word_tail")
    peek()
    a.jsr_abs("upcase")
    a.cmp_al(0x41).blo("sw_ret")
    a.cmp_al(0x5B).bhs("sw_ret")
    incz()
    a.jmp("skip_word_tail")
    a.label("sw_ret").rsr()

    # print_str_z: print up to closing quote (consumed) or CR (left)
    a.label("print_str_z")
    nextch()
    a.cmp_al(0x22).bne("ps_1")
    a.rsr()
    a.label("ps_1")
    a.cmp_al(0x0D).bne("ps_2")
    a.dcr("Z").rsr()
    a.label("ps_2")
    a.jsr_abs("putc").jmp("print_str_z")

    # var_addr: AL = upper-case letter -> Y = address of variable
    a.label("var_addr")
    a.cmp_al(0x41).blo("err_syntax")
    a.cmp_al(0x5B).bhs("err_syntax")
    a.ldbb_i(0x41).sabb().lda_i(0).xfrb_bl_al().sll_ax(1)
    a.ldb_i("VARS").aab().xfr("B", "Y").rsr()

    # ------------------------------------------------------------ numbers and expressions
    # accum_digit: AL = digit char; V_ACC = V_ACC * 10 + digit
    a.label("accum_digit")
    a.ldbb_i(0x30).sabb().lda_i(0).xfrb_bl_al()
    push_a()
    a.lda_i(10).xfr("A", "Y").lda_d("V_ACC").mulu("Y", "A")
    pop_a()
    a.aab().stb_d("V_ACC").rsr()

    a.label("parse_number")
    setw("V_ACC", 0)
    a.label("pn_loop")
    peek()
    not_digit("pn_done")
    incz()
    a.jsr_abs("accum_digit").jmp("pn_loop")
    a.label("pn_done")
    a.lda_d("V_ACC").rsr()

    # parse_lineno: G[.SS] -> A = G*100+SS (step digits: "1.1" means 1.10); V_HASDOT set if '.' seen
    a.label("parse_lineno")
    a.jsr_abs("parse_number")
    a.sta_d("V_T").lda_i(100).xfr("A", "Y").lda_d("V_T").mulu("Y", "A").stb_d("V_KEYT")
    setw("V_HASDOT", 0); setw("V_ACC", 0); setw("V_CNT", 0)
    peek()
    a.cmp_al(0x2E).bne("pl_done")
    incz()
    setw("V_HASDOT", 1)
    for i in range(2):
        peek()
        not_digit("pl_digits_done")
        incz()
        a.jsr_abs("accum_digit")
        a.lda_d("V_CNT").ina().sta_d("V_CNT")
    a.label("pl_digits_done")
    a.lda_d("V_CNT").cmp_ax(1).bne("pl_done")
    a.lda_i(10).xfr("A", "Y").lda_d("V_ACC").mulu("Y", "A").stb_d("V_ACC")
    a.label("pl_done")
    a.lda_d("V_KEYT").ldb_d("V_ACC").aab().xfr("B", "A").rsr()

    a.label("eval_factor")
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(ord("-")).bne("ef_1")
    incz(); a.jsr_abs("eval_factor"); neg_a(); a.rsr()
    a.label("ef_1")
    a.cmp_al(ord("+")).bne("ef_2")
    incz(); a.jmp("eval_factor")
    a.label("ef_2")
    a.cmp_al(ord("(")).bne("ef_3")
    incz(); a.jsr_abs("eval_expr"); push_a(); a.jsr_abs("skipsp"); nextch()
    a.cmp_al(ord(")")).bne("err_syntax")
    pop_a(); a.rsr()
    a.label("ef_3")
    not_digit("ef_var")
    a.jsr_abs("parse_number").rsr()
    a.label("ef_var")
    nextch(); a.jsr_abs("upcase").jsr_abs("var_addr").lda_x("Y").rsr()

    # signed_div: B = dividend, Y = divisor -> B = quotient
    a.label("signed_div")
    a.xfr("Y", "A")
    tst_a()
    a.bz("err_div0")
    setw("V_SIGN", 0)
    tst_b()
    a.bp("sd_1")
    a.lda_i(0).sab()
    a.lda_d("V_SIGN").ina().sta_d("V_SIGN")
    a.label("sd_1")
    a.xfr("Y", "A")
    tst_a()
    a.bp("sd_2")
    push_b(); a.xfr("Y", "B").lda_i(0).sab().xfr("B", "Y"); pop_b()
    a.lda_d("V_SIGN").ina().sta_d("V_SIGN")
    a.label("sd_2")
    a.xfr("B", "A").divu("Y", "A")
    a.stb_d("V_Q").lda_d("V_SIGN").cmp_ax(1).bne("sd_3")
    a.ldb_d("V_Q").lda_i(0).sab().rsr()
    a.label("sd_3").ldb_d("V_Q").rsr()

    a.label("eval_term")
    a.jsr_abs("eval_factor")
    a.label("et_loop")
    push_a()                                   # the accumulator must survive the peek
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(ord("*")).beq("et_mul")
    a.cmp_al(ord("/")).beq("et_div")
    pop_a(); a.rsr()
    a.label("et_mul")
    incz(); a.jsr_abs("eval_factor")
    a.xfr("A", "Y"); pop_a(); a.mulu("Y", "A").xfr("B", "A").jmp("et_loop")
    a.label("et_div")
    incz(); a.jsr_abs("eval_factor")
    a.xfr("A", "Y"); pop_b(); a.jsr_abs("signed_div").xfr("B", "A").jmp("et_loop")

    a.label("eval_expr")
    a.jsr_abs("eval_term")
    a.label("ee_loop")
    push_a()
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(ord("+")).beq("ee_add")
    a.cmp_al(ord("-")).beq("ee_sub")
    pop_a(); a.rsr()
    a.label("ee_add")
    incz(); a.jsr_abs("eval_term"); a.xfr("A", "B"); pop_a(); a.aab().xfr("B", "A").jmp("ee_loop")
    a.label("ee_sub")
    incz(); a.jsr_abs("eval_term"); a.xfr("A", "B"); pop_a(); a.sab().xfr("B", "A").jmp("ee_loop")

    # ------------------------------------------------------------ program store (64-byte slots: key, text, CR)
    a.label("clear_slots")
    a.lda_i("SLOTS").xfr("A", "Y")
    a.label("cs_loop")
    a.lda_i(0).sta_x("Y")
    for _ in range(4):
        a.inr("Y", 16)
    a.xfr("Y", "A").cmp_ax(SLOTS_END).blo("cs_loop").rsr()

    a.label("clear_all")
    a.jsr_abs("clear_slots")
    a.lda_i("VARS").xfr("A", "Y")
    a.label("ca_loop")
    a.lda_i(0).sta_x("Y", "+")
    a.xfr("Y", "A").cmp_ax(VARS + 52).blo("ca_loop").rsr()

    # scan_key: A = address of slot whose key == V_MK, or 0
    a.label("scan_key")
    a.lda_i("SLOTS").xfr("A", "Y")
    a.label("sk_loop")
    a.lda_x("Y").ldb_d("V_MK").sab().bnz("sk_next")
    a.xfr("Y", "A")
    tst_a()
    a.rsr()
    a.label("sk_next")
    for _ in range(4):
        a.inr("Y", 16)
    a.xfr("Y", "A").cmp_ax(SLOTS_END).blo("sk_loop")
    a.lda_i(0).rsr()

    # find_ge: A = slot with the smallest key >= V_KEY (0 if none)
    a.label("find_ge")
    setw("V_BEST", 0xFFFF); setw("V_BESTP", 0)
    a.lda_i("SLOTS").xfr("A", "Y")
    a.label("fg_loop")
    a.lda_x("Y").bz("fg_next")
    a.ldb_d("V_KEY").sab().bnc("fg_next")
    a.lda_x("Y").ldb_d("V_BEST").sab().bl("fg_next")
    a.lda_x("Y").sta_d("V_BEST").xfr("Y", "A").sta_d("V_BESTP")
    a.label("fg_next")
    for _ in range(4):
        a.inr("Y", 16)
    a.xfr("Y", "A").cmp_ax(SLOTS_END).blo("fg_loop")
    a.lda_d("V_BESTP").rsr()

    # store_line: Z at line number digits
    a.label("store_line")
    a.jsr_abs("parse_lineno")
    a.sta_d("V_NEWKEY").sta_d("V_MK")
    tst_a()
    a.bz("err_syntax")
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(0x0D).bne("sl_store")
    a.jsr_abs("scan_key").bz("sl_ret")             # delete
    a.xfr("A", "Y").lda_i(0).sta_x("Y")
    a.label("sl_ret").rsr()
    a.label("sl_store")
    a.jsr_abs("scan_key").bnz("sl_have")
    setw("V_MK", 0)
    a.jsr_abs("scan_key").bz("err_full")
    a.label("sl_have")
    a.xfr("A", "Y").lda_d("V_NEWKEY").sta_x("Y", "+")
    a.label("sl_copy")
    nextch()
    a.stab_x("Y", "+")
    a.cmp_al(0x0D).bne("sl_copy")
    a.rsr()

    # ------------------------------------------------------------ running
    # run_program: run lines with V_KEY <= key <= V_HI starting at the first line >= V_KEY
    a.label("run_program")
    a.label("rp_loop")
    a.lda_d("V_KEY").jsr_abs("find_ge").bz("rp_done")
    a.sta_d("V_PTR").xfr("A", "Y").lda_x("Y").sta_d("V_LINEKEY")
    a.lda_d("V_HI").ldb_d("V_LINEKEY").sab().bnc("rp_done")
    a.lda_d("V_PTR").ldb_i(2).aab().xfr("B", "Z")
    a.jsr_abs("exec_line")
    a.lda_d("V_QUIT").bnz("rp_done")
    a.lda_d("V_RET").bz("rp_noret")
    setw("V_RET", 0); setw("V_STOP", 0)
    a.rsr()
    a.label("rp_noret")
    a.lda_d("V_JUMP").bz("rp_seq")
    a.sta_d("V_KEY")
    setw("V_JUMP", 0); setw("V_STOP", 0)
    a.jmp("rp_loop")
    a.label("rp_seq")
    a.lda_d("V_LINEKEY").ina().sta_d("V_KEY").jmp("rp_loop")
    a.label("rp_done").rsr()

    # exec_line: execute statements at Z until CR (or a stop flag)
    a.label("exec_line")
    a.label("el_loop")
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(0x0D).bne("el_1")
    a.rsr()
    a.label("el_1")
    a.cmp_al(ord(";")).bne("el_cmd")
    incz()
    a.jmp("el_loop")
    a.label("el_cmd")
    nextch()
    a.jsr_abs("upcase").stab_d("V_CMD")
    a.jsr_abs("skip_word_tail")
    handlers = {"T": "h_type", "S": "h_set", "A": "h_ask", "I": "h_if", "G": "h_go", "D": "h_do",
                "F": "h_for", "R": "h_return", "Q": "h_quit", "C": "h_comment", "W": "h_write",
                "E": "h_erase"}
    for ch in COMMANDS:
        nxt = f"el_n_{ch}"
        a.ldab_d("V_CMD").cmp_al(ord(ch)).bne(nxt)
        a.jsr_abs(handlers[ch]).jmp("el_after")
        a.label(nxt)
    a.jmp_abs("err_syntax")
    a.label("el_after")
    a.lda_d("V_STOP").bz("el_loop")
    a.rsr()

    # ------------------------------------------------------------ statements
    a.label("h_comment").jsr_abs("skip_eol").rsr()
    a.label("h_return")
    setw("V_RET", 1); setw("V_STOP", 1); a.rsr()
    a.label("h_quit")
    setw("V_QUIT", 1); setw("V_STOP", 1); a.rsr()
    a.label("h_erase").jsr_abs("clear_slots").jsr_abs("skip_eol").rsr()

    a.label("h_type")
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(0x0D).bne("ht_1")
    a.rsr()
    a.label("ht_1")
    a.cmp_al(ord(";")).bne("ht_2")
    a.rsr()
    a.label("ht_2")
    a.cmp_al(ord(",")).bne("ht_3")
    incz(); a.jmp("h_type")
    a.label("ht_3")
    a.cmp_al(0x22).bne("ht_4")
    incz(); a.jsr_abs("print_str_z").jmp("h_type")
    a.label("ht_4")
    a.cmp_al(ord("!")).bne("ht_5")
    incz(); a.jsr_abs("crlf").jmp("h_type")
    a.label("ht_5")
    a.cmp_al(ord("#")).bne("ht_6")
    incz(); a.ldab_i(0x0D).jsr_abs("putc").jmp("h_type")
    a.label("ht_6")
    a.cmp_al(ord("%")).bne("ht_expr")
    incz()
    a.label("ht_fmt")
    peek()
    a.cmp_al(ord(".")).beq("ht_fmt_skip")
    not_digit("h_type")
    a.label("ht_fmt_skip")
    incz(); a.jmp("ht_fmt")
    a.label("ht_expr")
    a.jsr_abs("eval_expr").jsr_abs("print_number").jmp("h_type")

    a.label("h_set")
    a.jsr_abs("skipsp"); nextch(); a.jsr_abs("upcase").jsr_abs("var_addr")
    a.xfr("Y", "A"); push_a()
    a.jsr_abs("skipsp"); nextch()
    a.cmp_al(ord("=")).bne("err_syntax")
    a.jsr_abs("eval_expr")
    a.xfr("A", "B"); pop_a(); a.xfr("A", "Y").xfr("B", "A").sta_x("Y")
    a.rsr()

    a.label("h_ask")
    setw("V_STR", 0)
    a.label("ha_loop")
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(0x0D).bne("ha_1")
    a.rsr()
    a.label("ha_1")
    a.cmp_al(ord(";")).bne("ha_2")
    a.rsr()
    a.label("ha_2")
    a.cmp_al(ord(",")).bne("ha_3")
    incz(); a.jmp("ha_loop")
    a.label("ha_3")
    a.cmp_al(0x22).bne("ha_var")
    incz(); a.jsr_abs("print_str_z"); setw("V_STR", 1); a.jmp("ha_loop")
    a.label("ha_var")
    nextch(); a.jsr_abs("upcase").jsr_abs("var_addr")
    a.xfr("Y", "A"); push_a()
    a.lda_d("V_STR").bnz("ha_noprompt")
    a.ldab_i(ord(":")).jsr_abs("putc")
    a.label("ha_noprompt")
    setw("V_STR", 0)
    a.lda_i("INBUF").xfr("A", "Y").jsr_abs("read_line")
    a.xfr("Z", "A"); push_a()
    a.lda_i("INBUF").xfr("A", "Z").jsr_abs("eval_expr")
    a.xfr("A", "B"); pop_a(); a.xfr("A", "Z"); pop_a(); a.xfr("A", "Y").xfr("B", "A").sta_x("Y")
    a.jmp("ha_loop")

    a.label("h_go")
    a.jsr_abs("skipsp")
    peek()
    not_digit("go_none")
    a.jsr_abs("parse_lineno").jmp("go_set")
    a.label("go_none").lda_i(1)
    a.label("go_set").sta_d("V_JUMP")
    setw("V_STOP", 1)
    a.rsr()

    a.label("h_if")
    a.jsr_abs("skipsp"); nextch()
    a.cmp_al(ord("(")).bne("err_syntax")
    a.jsr_abs("eval_expr"); push_a()
    a.jsr_abs("skipsp"); nextch()
    a.cmp_al(ord(")")).bne("err_syntax")
    for v in ("V_L1", "V_L2", "V_L3"):
        setw(v, 0)
    for i, v in enumerate(("V_L1", "V_L2", "V_L3")):
        a.jsr_abs("skipsp")
        peek()
        not_digit("if_choose")
        a.jsr_abs("parse_lineno").sta_d(v)
        a.jsr_abs("skipsp")
        peek()
        a.cmp_al(ord(",")).bne("if_choose")
        incz()
    a.label("if_choose")
    pop_a()
    tst_a()
    a.bm("if_neg").bz("if_zero")
    a.lda_d("V_L3").jmp("if_go")
    a.label("if_neg").lda_d("V_L1").jmp("if_go")
    a.label("if_zero").lda_d("V_L2")
    a.label("if_go")
    a.bz("if_none")
    a.sta_d("V_JUMP")
    setw("V_STOP", 1)
    a.label("if_none").rsr()

    a.label("h_do")
    a.jsr_abs("skipsp").jsr_abs("parse_lineno")
    a.sta_d("V_LO")
    a.lda_d("V_HASDOT").bz("do_group")
    a.lda_d("V_LO").sta_d("V_HI2").jmp("do_go")
    a.label("do_group")
    a.lda_d("V_LO").ldb_i(99).aab().stb_d("V_HI2")
    a.label("do_go")
    a.xfr("Z", "A"); push_a()
    for v in ("V_KEY", "V_LINEKEY", "V_HI"):
        a.lda_d(v); push_a()
    a.lda_d("V_LO").sta_d("V_KEY").lda_d("V_HI2").sta_d("V_HI")
    a.jsr_abs("run_program")
    for v in ("V_HI", "V_LINEKEY", "V_KEY"):
        pop_a(); a.sta_d(v)
    pop_a(); a.xfr("A", "Z")
    a.rsr()

    # FOR v=a[,step],end[;body...]   frame: S+0 end, +2 step, +4 var addr, +6 body Z
    a.label("h_for")
    a.xfr("S", "A").ldb_i(0xFFF8).aab().xfr("B", "S")
    a.jsr_abs("skipsp"); nextch(); a.jsr_abs("upcase").jsr_abs("var_addr")
    a.xfr("Y", "A").sta_x("S", disp=4)
    a.jsr_abs("skipsp"); nextch()
    a.cmp_al(ord("=")).bne("err_syntax")
    a.jsr_abs("eval_expr")
    a.xfr("A", "B").lda_x("S", disp=4).xfr("A", "Y").xfr("B", "A").sta_x("Y")
    a.jsr_abs("skipsp"); nextch()
    a.cmp_al(ord(",")).bne("err_syntax")
    a.jsr_abs("eval_expr").sta_x("S", disp=0)
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(ord(",")).bne("for_two")
    incz()
    a.lda_x("S", disp=0).sta_x("S", disp=2)
    a.jsr_abs("eval_expr").sta_x("S", disp=0)
    a.jmp("for_body")
    a.label("for_two").lda_i(1).sta_x("S", disp=2)
    a.label("for_body")
    a.jsr_abs("skipsp")
    peek()
    a.cmp_al(ord(";")).bne("for_z")
    incz()
    a.label("for_z").xfr("Z", "A").sta_x("S", disp=6)
    a.label("fl_top")
    a.lda_x("S", disp=4).xfr("A", "Y")
    a.lda_x("S", disp=2).bm("fl_neg")
    a.lda_x("S", disp=0).ldb_x("Y").sab().bm("fl_exit").jmp("fl_body")
    a.label("fl_neg")
    a.lda_x("Y").ldb_x("S", disp=0).sab().bm("fl_exit")
    a.label("fl_body")
    a.lda_x("S", disp=6).xfr("A", "Z")
    a.jsr_abs("exec_line")
    a.lda_d("V_STOP").bnz("fl_exit")
    a.lda_x("S", disp=4).xfr("A", "Y").lda_x("Y").ldb_x("S", disp=2).aab().stb_x("Y")
    a.jmp("fl_top")
    a.label("fl_exit")
    a.jsr_abs("skip_eol")
    a.xfr("S", "A").ldb_i(8).aab().xfr("B", "S")
    a.rsr()

    # WRITE: list the program
    a.label("h_write")
    a.xfr("Z", "A"); push_a()
    setw("V_KEY", 1)
    a.label("hw_loop")
    a.lda_d("V_KEY").jsr_abs("find_ge").bz("hw_done")
    a.sta_d("V_PTR").xfr("A", "Y").lda_x("Y").sta_d("V_LINEKEY")
    a.lda_i(100).xfr("A", "Y").lda_d("V_LINEKEY").divu("Y", "A")
    push_a()
    a.xfr("B", "A").jsr_abs("print_number").ldab_i(ord(".")).jsr_abs("putc")
    pop_a(); a.jsr_abs("print_2digit")
    a.ldab_i(0x20).jsr_abs("putc")
    a.lda_d("V_PTR").ldb_i(2).aab().xfr("B", "Z")
    a.label("hw_text")
    nextch()
    a.cmp_al(0x0D).beq("hw_eol")
    a.jsr_abs("putc").jmp("hw_text")
    a.label("hw_eol")
    a.jsr_abs("crlf")
    a.lda_d("V_LINEKEY").ina().sta_d("V_KEY").jmp("hw_loop")
    a.label("hw_done")
    pop_a(); a.xfr("A", "Z").jsr_abs("skip_eol").rsr()

    # ------------------------------------------------------------ data
    for name, text in strings.items():
        a.label(name).asciz(text)

    code = a.bytes()
    hdr = b"CV" + LOAD.to_bytes(2, "big") * 2 + len(code).to_bytes(2, "big") + b"\x01"
    return hdr + code, a


