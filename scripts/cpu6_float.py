"""CPU6 decimal floating point for FOCAL (Stage 3).

Format (4 bytes, big-endian): byte0 = sign(0x80) | (exp10+64), bytes1-3 =
7-digit mantissa M (1000000..9999999) as a binary integer; the value is
M * 10^(exp10-6). Zero is all zero bytes. exp10 range +-38: overflow
sets fp_ovf, division by zero sets fp_divz. Values travel in A:B; the
second operand lives in fp_fop. Routines clobber A,B,X,Y, fp_* workspace.
Mantissa buffers fp_am/fp_bm are 4-byte big-endian binary integers.
"""


def declare_float_workspace(a):
    a.var("fp_fop", 4)
    a.var("fp_as"); a.var("fp_ae"); a.var("fp_am", 4)
    a.var("fp_bs"); a.var("fp_be"); a.var("fp_bm", 4)
    a.var("fp_pp", 8); a.var("fp_rr", 8); a.var("fp_qq", 4)
    a.var("fp_tmp"); a.var("fp_cnt"); a.var("fp_ovf"); a.var("fp_divz")
    a.var("fp_dig", 8); a.var("fp_perr")


def _buf10(a, tag, buf, n=4):
    # fp_m10_<tag>: buf (4-byte BE binary) *= 10
    a.label("fp_m10_" + tag)
    a.lda_i(0).sta_d("fp_tmp").lda_i(10).xfr("A", "Y")
    for i in range(n - 1, -1, -1):
        a.lda_i(0).ldbb_d(buf + "+" + str(i)).xfrb_bl_al()
        a.mulu("Y", "A")
        a.lda_d("fp_tmp").aab()
        a.xfrb_bl_al().stab_d(buf + "+" + str(i))
        a.div_imm(256, "B").stb_d("fp_tmp")
    a.rsr()
    # fp_d10_<tag>: buf /= 10; remainder (0..9) left in fp_tmp
    a.label("fp_d10_" + tag)
    a.lda_i(0).sta_d("fp_tmp")
    for i in range(n):
        a.lda_d("fp_tmp").sll_ax(8)
        a.ldbb_d(buf + "+" + str(i)).xfrb_bl_al()
        a.div_imm(10, "A")
        a.sta_d("fp_tmp")
        a.xfrb_bl_al().stab_d(buf + "+" + str(i))
    a.rsr()


def _unpack(a, side, src):
    s, e, m = "fp_" + side + "s", "fp_" + side + "e", "fp_" + side + "m"
    if src == "regs":
        a.sta_d("fp_qq").stb_d("fp_qq+2")
        src = "fp_qq"
    a.ldab_d(src).ldbb_i(0x80).andb_bl_al().stab_d(s + "+1")
    a.lda_i(0).ldab_d(src).ldbb_i(0x7F).andb_bl_al()
    a.ldb_i(64).sab().xfr("B", "A").sta_d(e)
    a.ldab_i(0).stab_d(m)
    for i in (1, 2, 3):
        a.ldab_d(src + "+" + str(i)).stab_d(m + "+" + str(i))


def _pack(a):
    a.label("fp_pack")
    a.lda_d("fp_am").bnz("fp_pk_nz")
    a.lda_d("fp_am+2").bnz("fp_pk_nz")
    a.lda_i(0).ldb_i(0).rsr()
    a.label("fp_pk_nz")
    for i in (1, 2, 3):
        a.ldab_d("fp_am+" + str(i)).stab_d("fp_qq+" + str(i))
    a.lda_d("fp_ae").ldb_i(64).aab().xfrb_bl_al().stab_d("fp_qq")
    a.lda_d("fp_as").bz("fp_pk_ld")
    a.ldab_d("fp_qq").ldbb_i(0x80).orb_bl_al().stab_d("fp_qq")
    a.label("fp_pk_ld")
    a.lda_d("fp_qq").ldb_d("fp_qq+2").rsr()


def _mzero(a, buf, lbl):
    a.lda_d(buf).bnz(lbl)
    a.lda_d(buf + "+2").bnz(lbl)


def _norm(a):
    # normalise fp_am/fp_ae to 7 digits; exp range check
    a.label("fp_norm")
    _mzero(a, "fp_am", "fp_n_1")
    a.rsr()
    a.label("fp_n_1")  # while M >= 10^7: M /= 10, e++
    a.lda_d("fp_am").cmp_ax(0x0098).bgt("fp_n_dn")
    a.bne("fp_n_2")
    a.lda_d("fp_am+2").cmp_ax(0x9680).bhs("fp_n_dn")
    a.jmp("fp_n_2")
    a.label("fp_n_dn")
    a.jsr_abs("fp_d10_a")
    a.lda_d("fp_ae").ina().sta_d("fp_ae").jmp("fp_n_1")
    a.label("fp_n_2")  # while M < 10^6: M *= 10, e--
    a.lda_d("fp_am").cmp_ax(0x000F).bgt("fp_n_ck")
    a.bne("fp_n_up")
    a.lda_d("fp_am+2").cmp_ax(0x4240).blo("fp_n_up")
    a.jmp("fp_n_ck")
    a.label("fp_n_up")
    a.jsr_abs("fp_m10_a")
    a.lda_d("fp_ae").ldb_i(0xFFFF).aab().stb_d("fp_ae").jmp("fp_n_1")
    a.label("fp_n_ck")
    a.lda_d("fp_ae").cmp_ax(38).ble("fp_n_lo")
    a.lda_i(1).sta_d("fp_ovf")
    a.label("fp_n_lo")
    a.lda_d("fp_ae").cmp_ax(-38).bm("fp_n_uf")
    a.rsr()
    a.label("fp_n_uf")
    a.lda_i(0).sta_d("fp_am").sta_d("fp_am+2").rsr()


def _copy_b_to_a(a):
    a.lda_d("fp_bs").sta_d("fp_as")
    a.lda_d("fp_be").sta_d("fp_ae")
    a.lda_d("fp_bm").sta_d("fp_am")
    a.lda_d("fp_bm+2").sta_d("fp_am+2")


def _emit_add(a):
    a.label("fp_add")
    _unpack(a, "a", "regs")
    _unpack(a, "b", "fp_fop")
    a.jmp("fp_ac")
    a.label("fp_sub")
    _unpack(a, "a", "regs")
    _unpack(a, "b", "fp_fop")
    a.lda_d("fp_bs").bz("fp_sb_1")
    a.lda_i(0).sta_d("fp_bs").jmp("fp_ac")
    a.label("fp_sb_1")
    a.lda_i(0x80).sta_d("fp_bs")
    a.label("fp_ac")
    _mzero(a, "fp_am", "fp_ac_az")
    _copy_b_to_a(a)
    a.jmp_abs("fp_pack")
    a.label("fp_ac_az")
    _mzero(a, "fp_bm", "fp_ac_bz")
    a.jmp_abs("fp_pack")
    a.label("fp_ac_bz")  # align exponents
    a.label("fp_ac_al")
    a.lda_d("fp_ae").ldb_d("fp_be").sab().bz("fp_ac_go")
    a.bm("fp_ac_bl")
    # ae > be: lower a exponent if it has room, else raise b
    a.lda_d("fp_am").cmp_ax(0x000F).bgt("fp_ac_bdn")
    a.bne("fp_ac_aup2")
    a.lda_d("fp_am+2").cmp_ax(0x4240).bhs("fp_ac_bdn")
    a.label("fp_ac_aup2")
    a.jsr_abs("fp_m10_a")
    a.lda_d("fp_ae").ldb_i(0xFFFF).aab().stb_d("fp_ae").jmp("fp_ac_al")
    a.label("fp_ac_bdn")
    a.jsr_abs("fp_d10_b")
    a.lda_d("fp_be").ina().sta_d("fp_be").jmp("fp_ac_al")
    a.label("fp_ac_bl")  # be > ae: lower b exponent if it has room, else raise a
    a.lda_d("fp_bm").cmp_ax(0x000F).bgt("fp_ac_adn")
    a.bne("fp_ac_bup2")
    a.lda_d("fp_bm+2").cmp_ax(0x4240).bhs("fp_ac_adn")
    a.label("fp_ac_bup2")
    a.jsr_abs("fp_m10_b")
    a.lda_d("fp_be").ldb_i(0xFFFF).aab().stb_d("fp_be").jmp("fp_ac_al")
    a.label("fp_ac_adn")
    a.jsr_abs("fp_d10_a")
    a.lda_d("fp_ae").ina().sta_d("fp_ae").jmp("fp_ac_al")
    a.label("fp_ac_go")
    a.lda_d("fp_as").ldb_d("fp_bs").sab().bnz("fp_ac_sub")
    # same sign: am += bm (4-byte add with carry)
    a.lda_d("fp_am+2").ldb_d("fp_bm+2").aab()
    a.bl("fp_ac_c1")
    a.stb_d("fp_am+2")
    a.lda_d("fp_am").ldb_d("fp_bm").aab().stb_d("fp_am")
    a.jmp("fp_ac_fin")
    a.label("fp_ac_c1")
    a.stb_d("fp_am+2")
    a.lda_d("fp_am").ldb_d("fp_bm").aab().inr("B").stb_d("fp_am")
    a.jmp("fp_ac_fin")
    a.label("fp_ac_sub")  # different signs: subtract smaller magnitude
    a.lda_d("fp_am").ldb_d("fp_bm").sab().bnz("fp_ac_shi")
    a.lda_d("fp_am+2").ldb_d("fp_bm+2").sab().bnz("fp_ac_slo")
    a.lda_i(0).sta_d("fp_am").sta_d("fp_am+2").jmp_abs("fp_pack")
    a.label("fp_ac_shi")
    a.bhs("fp_ac_ab")
    a.jmp("fp_ac_ba")
    a.label("fp_ac_slo")
    a.bhs("fp_ac_ab")
    a.jmp("fp_ac_ba")
    a.label("fp_ac_ab")  # am -= bm, sign stays a
    a.lda_d("fp_am+2").ldb_d("fp_bm+2").sab()
    a.bnc("fp_ac_ab1")
    a.stb_d("fp_am+2")
    a.lda_i(0).sta_d("fp_tmp")
    a.jmp("fp_ac_ab2")
    a.label("fp_ac_ab1")
    a.stb_d("fp_am+2")
    a.lda_i(1).sta_d("fp_tmp")
    a.label("fp_ac_ab2")
    a.lda_d("fp_am").ldb_d("fp_bm").sab()
    a.lda_d("fp_tmp").bz("fp_ac_ab3")
    a.dcr("B")
    a.label("fp_ac_ab3")
    a.stb_d("fp_am").jmp("fp_ac_fin")
    a.label("fp_ac_ba")  # am = bm - am, sign becomes b
    a.lda_d("fp_bs").sta_d("fp_as")
    a.lda_d("fp_bm+2").ldb_d("fp_am+2").sab()
    a.bnc("fp_ac_ba1")
    a.stb_d("fp_qq")
    a.lda_i(0).sta_d("fp_tmp")
    a.jmp("fp_ac_ba2")
    a.label("fp_ac_ba1")
    a.stb_d("fp_qq")
    a.lda_i(1).sta_d("fp_tmp")
    a.label("fp_ac_ba2")
    a.lda_d("fp_bm").ldb_d("fp_am").sab()
    a.lda_d("fp_tmp").bz("fp_ac_ba3")
    a.dcr("B")
    a.label("fp_ac_ba3")
    a.stb_d("fp_am")
    a.lda_d("fp_qq").sta_d("fp_am+2")
    a.label("fp_ac_fin")
    a.jsr_abs("fp_norm")
    a.jmp_abs("fp_pack")


def _emit_neg(a):
    a.label("fp_neg")
    a.sta_d("fp_qq").stb_d("fp_qq+2")
    a.lda_d("fp_qq").ldb_i(0x7FFF).nab().bnz("fp_ng_1")
    a.lda_d("fp_qq+2").bnz("fp_ng_1")
    a.lda_d("fp_qq").ldb_d("fp_qq+2").rsr()
    a.label("fp_ng_1")
    a.lda_d("fp_qq").ldb_i(0x8000).aab().xfr("B", "A")
    a.ldb_d("fp_qq+2").rsr()


def _add32(a, tag, off):
    # add X(hi):Y(lo) into fp_pp words at off (hi) and off+2 (lo)
    pp, pp2 = "fp_pp+" + str(off), "fp_pp+" + str(off + 2)
    a.lda_d(pp2).xfr("Y", "B").aab()
    a.bl(tag + "_c")
    a.stb_d(pp2)
    a.lda_d(pp).ldb_d("fp_tmp").aab().stb_d(pp)
    a.jmp(tag + "_d")
    a.label(tag + "_c")
    a.stb_d(pp2)
    a.lda_d(pp).ldb_d("fp_tmp").aab().inr("B").stb_d(pp)
    a.label(tag + "_d")


def _emit_mul(a):
    a.label("fp_mul")
    _unpack(a, "a", "regs")
    _unpack(a, "b", "fp_fop")
    _mzero(a, "fp_am", "fp_mu_z")
    a.lda_i(0).ldb_i(0).rsr()
    a.label("fp_mu_z")
    _mzero(a, "fp_bm", "fp_mu_nz")
    a.lda_i(0).ldb_i(0).rsr()
    a.label("fp_mu_nz")
    a.lda_d("fp_bs").bz("fp_mu_s")
    a.lda_d("fp_as").bz("fp_mu_s1")
    a.lda_i(0).sta_d("fp_as").jmp("fp_mu_s")
    a.label("fp_mu_s1")
    a.lda_i(0x80).sta_d("fp_as")
    a.label("fp_mu_s")
    a.lda_d("fp_ae").ldb_d("fp_be").aab().xfr("B", "A").ldb_i(0xFFFA).aab().stb_d("fp_ae")
    a.lda_i(0).sta_d("fp_pp").sta_d("fp_pp+2").sta_d("fp_pp+4")
    # p0 = al*bl -> add32 at word offset 2
    a.lda_d("fp_am+2").ldb_d("fp_bm+2").xfr("B", "Y").mulu("Y", "A")
    a.sta_d("fp_tmp").xfr("B", "Y")
    _add32(a, "fp_mu_p0", 2)
    # p1 = ah*bl -> add32 at offset 0
    a.lda_d("fp_am").ldb_d("fp_bm+2").xfr("B", "Y").mulu("Y", "A")
    a.sta_d("fp_tmp").xfr("B", "Y")
    _add32(a, "fp_mu_p1", 0)
    # p2 = al*bh -> add32 at offset 0
    a.lda_d("fp_am+2").ldb_d("fp_bm").xfr("B", "Y").mulu("Y", "A")
    a.sta_d("fp_tmp").xfr("B", "Y")
    _add32(a, "fp_mu_p2", 0)
    # p3 = ah*bh (fits 16 bits) -> add into top word
    a.lda_d("fp_am").ldb_d("fp_bm").xfr("B", "Y").mulu("Y", "A")
    a.lda_d("fp_pp").aab().stb_d("fp_pp")
    a.jmp("fp_mu_nm")
    a.label("fp_mu_nm")  # pp is 6-byte product; normalise to 7 digits
    a.label("fp_mu_d")
    a.lda_d("fp_pp").bnz("fp_mu_dd")
    a.lda_d("fp_pp+2").ldb_i(0x0098).sab().bnc("fp_mu_u")
    a.bz("fp_mu_de")
    a.jmp("fp_mu_dd")
    a.label("fp_mu_de")
    a.lda_d("fp_pp+4").ldb_i(0x9680).sab().bhs("fp_mu_dd")
    a.jmp("fp_mu_u")
    a.label("fp_mu_dd")
    a.jsr_abs("fp_d10_p")
    a.lda_d("fp_ae").ina().sta_d("fp_ae").jmp("fp_mu_d")
    a.label("fp_mu_u")
    a.lda_d("fp_pp").bnz("fp_mu_cp")
    a.lda_d("fp_pp+2").ldb_i(0x000F).sab().bhs("fp_mu_ue")
    a.jmp("fp_mu_uu")
    a.label("fp_mu_ue")
    a.bnz("fp_mu_cp")
    a.lda_d("fp_pp+4").ldb_i(0x4240).sab().bnc("fp_mu_uu")
    a.jmp("fp_mu_cp")
    a.label("fp_mu_uu")
    a.jsr_abs("fp_m10_p")
    a.lda_d("fp_ae").ldb_i(0xFFFF).aab().stb_d("fp_ae").jmp("fp_mu_u")
    a.label("fp_mu_cp")
    a.lda_d("fp_pp+2").sta_d("fp_am")
    a.lda_d("fp_pp+4").sta_d("fp_am+2")
    a.jsr_abs("fp_norm")
    a.jmp_abs("fp_pack")


def _shl(a, tag, buf, n):
    # fp_shl_<tag>: buf (n bytes BE) <<= 1; carry in/out via fp_tmp
    a.label("fp_shl_" + tag)
    for i in range(n - 1, -1, -1):
        a.lda_i(0).ldbb_d(buf + "+" + str(i)).xfrb_bl_al()
        a.xfr("A", "B").aab()
        a.lda_d("fp_tmp").aab()
        a.xfr("B", "A").stab_d(buf + "+" + str(i))
        a.cmp_ax(256).bhs("fp_shl_" + tag + "_" + str(i))
        a.lda_i(0).sta_d("fp_tmp").jmp("fp_shl_" + tag + "d" + str(i))
        a.label("fp_shl_" + tag + "_" + str(i))
        a.lda_i(1).sta_d("fp_tmp")
        a.label("fp_shl_" + tag + "d" + str(i))
    a.rsr()


def _emit_div(a):
    a.label("fp_div")
    _unpack(a, "a", "regs")
    _unpack(a, "b", "fp_fop")
    _mzero(a, "fp_bm", "fp_dv_ok")
    a.lda_i(1).sta_d("fp_divz")
    a.lda_i(0).ldb_i(0).rsr()
    a.label("fp_dv_ok")
    _mzero(a, "fp_am", "fp_dv_nz")
    a.lda_i(0).ldb_i(0).rsr()
    a.label("fp_dv_nz")
    a.lda_d("fp_bs").bz("fp_dv_s")
    a.lda_d("fp_as").bz("fp_dv_s1")
    a.lda_i(0).sta_d("fp_as").jmp("fp_dv_s")
    a.label("fp_dv_s1")
    a.lda_i(0x80).sta_d("fp_as")
    a.label("fp_dv_s")
    a.lda_d("fp_ae").ldb_d("fp_be").sab().xfr("B", "A")
    a.ldb_i(1).sab().stb_d("fp_ae")
    # N = am * 10^7 into fp_rr (6 bytes)
    a.lda_i(0).sta_d("fp_rr").sta_d("fp_qq").sta_d("fp_qq+2")
    a.lda_d("fp_am").sta_d("fp_rr+2")
    a.lda_d("fp_am+2").sta_d("fp_rr+4")
    a.lda_i(0).sta_d("fp_pp").sta_d("fp_pp+2").sta_d("fp_pp+4")
    for _ in range(7):
        a.jsr_abs("fp_m10_r")
    a.lda_i(48).sta_d("fp_cnt")
    a.label("fp_dv_lp")
    a.lda_i(0).sta_d("fp_tmp")
    a.jsr_abs("fp_shl_r")
    a.jsr_abs("fp_shl_p")
    a.lda_i(0).sta_d("fp_tmp")
    a.jsr_abs("fp_shl_q")
    # if R (fp_pp) >= Bm: R -= Bm and set Q low bit
    a.lda_d("fp_pp").bnz("fp_dv_ge")
    a.lda_d("fp_pp+2").ldb_d("fp_bm").sab().bnz("fp_dv_ch")
    a.lda_d("fp_pp+4").ldb_d("fp_bm+2").sab().bhs("fp_dv_ge")
    a.jmp("fp_dv_nx")
    a.label("fp_dv_ch")
    a.bhs("fp_dv_ge")
    a.jmp("fp_dv_nx")
    a.label("fp_dv_ge")
    a.ldab_i(0).stab_d("fp_pp+7")
    for off, bm in ((4, "fp_bm+2"), (2, "fp_bm"), (0, None)):
        t = "fp_dv_s" + str(off)
        if bm:
            a.ldb_d(bm)
        else:
            a.ldb_i(0)
        a.ldab_d("fp_pp+7").bz(t + "n")
        a.inr("B")
        a.label(t + "n")
        a.lda_d("fp_pp+" + str(off))
        a.sab().bnc(t + "b")
        a.stb_d("fp_pp+" + str(off))
        a.ldab_i(0).stab_d("fp_pp+7").jmp(t + "d")
        a.label(t + "b")
        a.stb_d("fp_pp+" + str(off))
        a.ldab_i(1).stab_d("fp_pp+7")
        a.label(t + "d")
    a.lda_d("fp_qq+2").ina().sta_d("fp_qq+2")
    a.label("fp_dv_nx")
    a.lda_d("fp_cnt").ldb_i(0xFFFF).aab().stb_d("fp_cnt")
    a.bnz("fp_dv_lp")
    a.lda_d("fp_qq").sta_d("fp_am")
    a.lda_d("fp_qq+2").sta_d("fp_am+2")
    a.jsr_abs("fp_norm")
    a.jmp_abs("fp_pack")


def _emit_cmp(a):
    a.label("fp_cmp")  # FAC vs fp_fop -> A = -1, 0, 1
    _unpack(a, "a", "regs")
    _unpack(a, "b", "fp_fop")
    _mzero(a, "fp_am", "fp_cm_az")
    _mzero(a, "fp_bm", "fp_cm_0")
    a.lda_d("fp_bs").bnz("fp_cm_p1")
    a.lda_i(-1).rsr()
    a.label("fp_cm_p1")
    a.lda_i(1).rsr()
    a.label("fp_cm_0")
    a.lda_i(0).rsr()
    a.label("fp_cm_az")
    _mzero(a, "fp_bm", "fp_cm_bz")
    a.lda_d("fp_as").bnz("fp_cm_m1")
    a.lda_i(1).rsr()
    a.label("fp_cm_m1")
    a.lda_i(-1).rsr()
    a.label("fp_cm_bz")
    a.lda_d("fp_as").ldb_d("fp_bs").sab().bz("fp_cm_sm")
    a.lda_d("fp_as").bnz("fp_cm_m1")
    a.lda_i(1).rsr()
    a.label("fp_cm_sm")  # same sign: compare magnitudes
    a.lda_d("fp_ae").ldb_d("fp_be").sab().bm("fp_cm_lt")
    a.bgz("fp_cm_gt")
    a.lda_d("fp_am").ldb_d("fp_bm").sab().bnz("fp_cm_h")
    a.lda_d("fp_am+2").ldb_d("fp_bm+2").sab().bnz("fp_cm_l")
    a.jmp("fp_cm_0")
    a.label("fp_cm_h")
    a.bhs("fp_cm_gt")
    a.jmp("fp_cm_lt")
    a.label("fp_cm_l")
    a.bhs("fp_cm_gt")
    a.jmp("fp_cm_lt")
    a.label("fp_cm_gt")
    a.lda_d("fp_as").bnz("fp_cm_m1")
    a.lda_i(1).rsr()
    a.label("fp_cm_lt")
    a.lda_d("fp_as").bnz("fp_cm_p1")
    a.lda_i(-1).rsr()


def _emit_conv(a):
    a.label("fp_from_i16")  # A = signed int -> A:B float
    a.sta_d("fp_am+2")
    a.lda_i(0).sta_d("fp_am").sta_d("fp_as")
    a.lda_d("fp_am+2").bz("fp_fi_z")
    a.bp("fp_fi_n")
    a.lda_i(0x80).sta_d("fp_as")
    a.lda_i(0).ldb_d("fp_am+2").sab().stb_d("fp_am+2")
    a.label("fp_fi_n")
    a.lda_i(6).sta_d("fp_ae")
    a.jsr_abs("fp_norm")
    a.jmp_abs("fp_pack")
    a.label("fp_fi_z")
    a.lda_i(0).ldb_i(0).rsr()
    a.label("fp_to_i16")  # A:B float -> A = truncated int, clamped
    _unpack(a, "a", "regs")
    a.lda_d("fp_am").sta_d("fp_qq")
    a.lda_d("fp_am+2").sta_d("fp_qq+2")
    a.lda_d("fp_ae").ldb_i(6).sab().stb_d("fp_cnt")
    a.bz("fp_ti_sg")
    a.bm("fp_ti_dn")
    a.label("fp_ti_up")  # multiply qq by 10, cnt times
    a.lda_d("fp_qq").bnz("fp_ti_cl")
    a.lda_d("fp_qq+2").cmp_ax(3277).bhs("fp_ti_cl")
    a.jsr_abs("fp_m10_q")
    a.lda_d("fp_cnt").ldb_i(0xFFFF).aab().stb_d("fp_cnt")
    a.bnz("fp_ti_up")
    a.jmp("fp_ti_sg")
    a.label("fp_ti_dn")  # divide by 10, -cnt times
    a.lda_d("fp_cnt").cmp_ax(-7).bm("fp_ti_z")
    a.jsr_abs("fp_d10_q")
    a.lda_d("fp_cnt").ina().sta_d("fp_cnt")
    a.bnz("fp_ti_dn")
    a.jmp("fp_ti_sg")
    a.label("fp_ti_z")
    a.lda_i(0).sta_d("fp_qq+2").jmp("fp_ti_sg")
    a.label("fp_ti_cl")
    a.lda_i(32767).sta_d("fp_qq+2")
    a.label("fp_ti_sg")
    a.lda_d("fp_qq+2").cmp_ax(32767).ble("fp_ti_sc")
    a.lda_i(32767).sta_d("fp_qq+2")
    a.label("fp_ti_sc")
    a.lda_d("fp_as").bz("fp_ti_ld")
    a.lda_d("fp_qq+2").xfr("A", "B").lda_i(0).sab().xfr("B", "A").rsr()
    a.label("fp_ti_ld")
    a.lda_d("fp_qq+2").rsr()


def _emit_parse(a):
    # fp_parse: Z -> text; returns A:B value, Z past the number.
    # state bytes in fp_qq: +0 sign, +1 any-digit, +2 in-frac, +3 scale
    a.label("fp_parse")
    a.lda_i(0).sta_d("fp_am").sta_d("fp_am+2").sta_d("fp_as")
    a.sta_d("fp_qq").sta_d("fp_qq+2").sta_d("fp_perr")
    a.ldab_z(0).cmp_al(0x2B).bne("fp_pa_s")
    a.inr_z().jmp("fp_pa_m")
    a.label("fp_pa_s")
    a.ldab_z(0).cmp_al(0x2D).bne("fp_pa_m")
    a.ldab_i(0x80).stab_d("fp_qq")
    a.inr_z()
    a.label("fp_pa_m")
    a.label("fp_pa_lp")
    a.ldab_z(0)
    a.cmp_al(0x30).blo("fp_pa_nd")
    a.cmp_al(0x3A).bhs("fp_pa_nd")
    a.inr_z()
    a.ldbb_i(0x30).sabb().lda_i(0).xfrb_bl_al().sta_d("fp_cnt")
    a.ldab_i(1).stab_d("fp_qq+1")
    # append if fp_am < 10^6
    a.lda_d("fp_am").cmp_ax(0x000F).bgt("fp_pa_no")
    a.bne("fp_pa_ap")
    a.lda_d("fp_am+2").cmp_ax(0x4240).bhs("fp_pa_no")
    a.label("fp_pa_ap")
    a.jsr_abs("fp_m10_a")
    a.lda_d("fp_am+2").ldb_d("fp_cnt").aab()
    a.bl("fp_pa_cy")
    a.stb_d("fp_am+2").jmp("fp_pa_sc")
    a.label("fp_pa_cy")
    a.stb_d("fp_am+2")
    a.lda_d("fp_am").ina().sta_d("fp_am")
    a.label("fp_pa_sc")  # fraction digit: scale--
    a.ldab_d("fp_qq+2").bz("fp_pa_lp")
    a.ldab_d("fp_qq+3").ldbb_i(1).sabb().xfrb_bl_al().stab_d("fp_qq+3")
    a.jmp("fp_pa_lp")
    a.label("fp_pa_no")  # digit dropped: integer digit means scale++
    a.ldab_d("fp_qq+2").bnz("fp_pa_lp")
    a.ldab_d("fp_qq+3").ldbb_i(0xFF).sabb().xfrb_bl_al().stab_d("fp_qq+3")
    a.jmp("fp_pa_lp")
    a.label("fp_pa_nd")
    a.ldab_z(0).cmp_al(0x2E).bne("fp_pa_ex")
    a.ldab_d("fp_qq+2").bnz("fp_pa_ex")
    a.inr_z()
    a.ldab_i(1).stab_d("fp_qq+2")
    a.jmp("fp_pa_lp")
    a.label("fp_pa_ex")
    a.ldab_z(0).cmp_al(0x45).beq("fp_pa_e1")
    a.cmp_al(0x65).bne("fp_pa_fin")
    a.label("fp_pa_e1")
    a.xfr("Z", "A").sta_d("fp_tmp")  # save Z in case E has no digits
    a.inr_z()
    a.ldab_i(0).stab_d("fp_dig+4").stab_d("fp_dig+5").stab_d("fp_dig+6")
    a.ldab_z(0).cmp_al(0x2D).bne("fp_pa_e2")
    a.ldab_i(1).stab_d("fp_dig+4")
    a.inr_z().jmp("fp_pa_el")
    a.label("fp_pa_e2")
    a.ldab_z(0).cmp_al(0x2B).bne("fp_pa_el")
    a.inr_z()
    a.label("fp_pa_el")
    a.ldab_z(0)
    a.cmp_al(0x30).blo("fp_pa_ed")
    a.cmp_al(0x3A).bhs("fp_pa_ed")
    a.inr_z()
    a.ldbb_i(0x30).sabb().lda_i(0).xfrb_bl_al().sta_d("fp_cnt")
    a.ldab_i(1).stab_d("fp_dig+6")
    a.lda_i(0).ldab_d("fp_dig+5").ldb_i(10).xfr("B", "Y")
    a.mulu("Y", "A").lda_d("fp_cnt").aab().xfr("B", "A")
    a.cmp_ax(200).blo("fp_pa_ev")
    a.lda_i(200)
    a.label("fp_pa_ev")
    a.stab_d("fp_dig+5")
    a.jmp("fp_pa_el")
    a.label("fp_pa_ed")
    a.ldab_d("fp_dig+6").bnz("fp_pa_ea")
    a.lda_d("fp_tmp").xfr("A", "Z").jmp("fp_pa_fin")
    a.label("fp_pa_ea")  # scale += +-expval (word math, sign-extended)
    a.lda_i(0).ldab_d("fp_qq+3")
    a.cmp_ax(128).blo("fp_pa_sx")
    a.ldb_i(256).sab().xfr("B", "A")
    a.label("fp_pa_sx")
    a.sta_d("fp_cnt")
    a.lda_i(0).ldab_d("fp_dig+5").xfr("A", "B")
    a.ldab_d("fp_dig+4").bnz("fp_pa_es")
    a.lda_d("fp_cnt").aab().jmp("fp_pa_st")
    a.label("fp_pa_es")
    a.lda_d("fp_cnt").sab()
    a.label("fp_pa_st")
    a.xfrb_bl_al().stab_d("fp_qq+3")
    a.label("fp_pa_fin")
    a.ldab_d("fp_qq+1").bnz("fp_pa_ok")
    a.lda_i(1).sta_d("fp_perr")
    a.lda_i(0).ldb_i(0).rsr()
    a.label("fp_pa_ok")
    a.ldab_d("fp_qq").stab_d("fp_as+1")
    a.lda_i(0).ldab_d("fp_qq+3")
    a.cmp_ax(128).blo("fp_pa_fx")
    a.ldb_i(256).sab().xfr("B", "A")
    a.label("fp_pa_fx")
    a.ldb_i(6).aab().stb_d("fp_ae")
    a.jsr_abs("fp_norm")
    a.jmp_abs("fp_pack")


def _putc(a, ch):
    a.lda_i(ch).jsr_abs("putc")


def _emit_print(a):
    a.label("fp_print")  # A:B value -> console via putc
    _unpack(a, "a", "regs")
    _mzero(a, "fp_am", "fp_pr_nz")
    _putc(a, 0x30)
    a.rsr()
    a.label("fp_pr_nz")
    a.lda_d("fp_as").bz("fp_pr_s")
    _putc(a, 0x2D)
    a.label("fp_pr_s")  # round mantissa to 6 digits into fp_qq
    a.lda_d("fp_am").sta_d("fp_qq")
    a.lda_d("fp_am+2").sta_d("fp_qq+2")
    a.jsr_abs("fp_d10_q")
    a.lda_d("fp_tmp").cmp_ax(5).blo("fp_pr_d")
    a.lda_d("fp_qq+2").ina().sta_d("fp_qq+2").bnz("fp_pr_d")
    a.lda_d("fp_qq").ina().sta_d("fp_qq")
    a.label("fp_pr_d")  # 10^6 after rounding? -> 100000, exp++
    a.lda_d("fp_qq").cmp_ax(0x000F).bne("fp_pr_x")
    a.lda_d("fp_qq+2").cmp_ax(0x4240).bne("fp_pr_x")
    a.lda_i(1).sta_d("fp_qq")
    a.lda_i(0x86A0).sta_d("fp_qq+2")
    a.lda_d("fp_ae").ina().sta_d("fp_ae")
    a.label("fp_pr_x")  # extract 6 digits, fp_dig[0..5]
    for i in (5, 4, 3, 2, 1, 0):
        a.jsr_abs("fp_d10_q")
        a.lda_d("fp_tmp").stab_d("fp_dig+" + str(i))
    # lastnz -> fp_dig+7
    a.lda_i(5).sta_d("fp_cnt")
    a.label("fp_pr_lz")
    a.lda_label("fp_dig").ldb_d("fp_cnt").aab().xfr("B", "Z")
    a.ldab_z(0).bnz("fp_pr_lz2")
    a.lda_d("fp_cnt").ldb_i(0xFFFF).aab().stb_d("fp_cnt").jmp("fp_pr_lz")
    a.label("fp_pr_lz2")
    a.lda_d("fp_cnt").stab_d("fp_dig+7")
    # fixed if -3 <= exp <= 6
    a.lda_d("fp_ae").cmp_ax(-3).bm("fp_pr_sci")
    a.lda_d("fp_ae").cmp_ax(6).bgt("fp_pr_sci")
    a.lda_d("fp_ae").bm("fp_pr_ng")
    # fixed, exp >= 0: E+1 integer digits
    a.lda_d("fp_ae").ina().sta_d("fp_cnt")
    a.lda_i(0).sta_d("fp_tmp")
    a.label("fp_pr_il")
    a.lda_d("fp_tmp").cmp_ax(6).bhs("fp_pr_z")
    a.lda_label("fp_dig").ldb_d("fp_tmp").aab().xfr("B", "Z")
    a.lda_i(0).ldab_z(0).ldb_i(0x30).aab().xfr("B", "A").jsr_abs("putc")
    a.jmp("fp_pr_in")
    a.label("fp_pr_z")
    _putc(a, 0x30)
    a.label("fp_pr_in")
    a.lda_d("fp_tmp").ina().sta_d("fp_tmp")
    a.lda_d("fp_cnt").ldb_i(0xFFFF).aab().stb_d("fp_cnt")
    a.bnz("fp_pr_il")
    # fraction digits dig[E+1 .. lastnz]
    a.lda_d("fp_ae").ina().stab_d("fp_dig+6")
    a.lda_i(0).ldab_d("fp_dig+6").sta_d("fp_tmp")
    a.lda_i(0).ldab_d("fp_dig+7").ldb_d("fp_tmp").sab()
    a.bm("fp_pr_dn")
    _putc(a, 0x2E)
    a.label("fp_pr_fl")
    a.lda_i(0).ldab_d("fp_dig+6").xfr("A", "B")
    a.lda_label("fp_dig").aab().xfr("B", "Z")
    a.lda_i(0).ldab_z(0).ldb_i(0x30).aab().xfr("B", "A").jsr_abs("putc")
    a.ldab_d("fp_dig+6").ina().stab_d("fp_dig+6")
    a.lda_i(0).ldab_d("fp_dig+6").sta_d("fp_tmp")
    a.lda_i(0).ldab_d("fp_dig+7").ldb_d("fp_tmp").sab()
    a.bm("fp_pr_dn")
    a.jmp("fp_pr_fl")
    a.label("fp_pr_dn")
    a.rsr()
    a.label("fp_pr_ng")  # fixed, exp < 0: 0.00ddd
    _putc(a, 0x30)
    _putc(a, 0x2E)
    a.lda_d("fp_ae").xfr("A", "B").lda_i(0).sab().dcr("B")
    a.stb_d("fp_cnt")
    a.label("fp_pr_zl")
    a.lda_d("fp_cnt").bz("fp_pr_zd")
    _putc(a, 0x30)
    a.lda_d("fp_cnt").ldb_i(0xFFFF).aab().stb_d("fp_cnt")
    a.jmp("fp_pr_zl")
    a.label("fp_pr_zd")
    a.ldab_i(0).stab_d("fp_dig+6")
    a.jmp("fp_pr_fl")
    a.label("fp_pr_sci")  # 0.ddddddE+XX (Nova style)
    _putc(a, 0x30)
    _putc(a, 0x2E)
    a.lda_i(0).sta_d("fp_tmp")
    a.label("fp_pr_sl")
    a.lda_label("fp_dig").ldb_d("fp_tmp").aab().xfr("B", "Z")
    a.lda_i(0).ldab_z(0).ldb_i(0x30).aab().xfr("B", "A").jsr_abs("putc")
    a.lda_d("fp_tmp").ina().sta_d("fp_tmp")
    a.lda_d("fp_tmp").cmp_ax(6).bne("fp_pr_sl")
    _putc(a, 0x45)
    a.lda_d("fp_ae").ina().sta_d("fp_cnt")
    a.bm("fp_pr_sn")
    _putc(a, 0x2B)
    a.jmp("fp_pr_s2")
    a.label("fp_pr_sn")
    _putc(a, 0x2D)
    a.lda_i(0).ldb_d("fp_cnt").sab().stb_d("fp_cnt")
    a.label("fp_pr_s2")
    a.lda_d("fp_cnt").cmp_ax(99).ble("fp_pr_s3")
    a.lda_i(99).sta_d("fp_cnt")
    a.label("fp_pr_s3")
    a.lda_d("fp_cnt").div_imm(10, "A").sta_d("fp_tmp")
    a.xfr("B", "A").ldb_i(0x30).aab().xfr("B", "A").jsr_abs("putc")
    a.lda_d("fp_tmp").ldb_i(0x30).aab().xfr("B", "A").jsr_abs("putc")
    a.rsr()


def _emit_trunc(a):
    # fp_trunc: A:B = integer part of A:B, truncated toward zero (FITR).
    a.label("fp_trunc")
    _unpack(a, "a", "regs")
    _mzero(a, "fp_am", "fp_tr_nz")
    a.jmp("fp_pack")
    a.label("fp_tr_nz")
    a.lda_i(6).ldb_d("fp_ae").sab().xfr("B", "A")
    a.cmp_ax(0).ble("fp_tr_pk")
    a.cmp_ax(6).bgt("fp_tr_z")
    a.sta_d("fp_cnt")
    a.label("fp_tr_lp")
    a.jsr_abs("fp_d10_a")
    a.lda_d("fp_cnt").ldb_i(0xFFFF).aab().stb_d("fp_cnt")
    a.lda_d("fp_cnt").bnz("fp_tr_lp")
    a.lda_i(6).sta_d("fp_ae")
    a.jsr_abs("fp_norm")
    a.jmp("fp_pack")
    a.label("fp_tr_z")
    a.lda_i(0).sta_d("fp_am").sta_d("fp_am+2")
    a.jmp("fp_pack")
    a.label("fp_tr_pk")
    a.jmp("fp_pack")


def emit_float_routines(a):
    _buf10(a, "a", "fp_am")
    _buf10(a, "b", "fp_bm")
    _buf10(a, "p", "fp_pp", 6)
    _buf10(a, "r", "fp_rr", 6)
    _buf10(a, "q", "fp_qq")
    _shl(a, "r", "fp_rr", 6)
    _shl(a, "p", "fp_pp", 6)
    _shl(a, "q", "fp_qq", 4)
    _pack(a)
    _norm(a)
    _emit_neg(a)
    _emit_add(a)
    _emit_mul(a)
    _emit_div(a)
    _emit_cmp(a)
    _emit_trunc(a)
    _emit_conv(a)
    _emit_parse(a)
    _emit_print(a)
