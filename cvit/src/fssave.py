"""Kernel CVIT filesystem write path (SVC 0x58 SAVE) and RUN loader
(SVC 0x56) for the stage-2 kernel (ME-4).

Emitted into the stage-2 kernel by build_stage2.py after
emit_fs_load: the directory scan (fs_scan), multiply (fs_mul),
literal compare (fs_cmplit) and the workspace cells of fsload.py
are reused. SAVE mirrors the host FocalSave and
CvitFileSystem.WriteTextMember semantics (per decision D2 the
kernel owns the slots-to-text serialization): the FOCAL slots are
serialized in key order, a missing member is created sized by
ceil(len/400) sectors, a member that outgrows its capacity is
relocated to a fresh append-only extent, and the UAL allocation
list and high-water word are maintained exactly as the host
maintains them. RUN mirrors the host RunSystemMember: the command
string is read from 0x2F00, CV members are copied to their load
address and entered with a JSR-style frame (old RT pushed on the
caller stack, RT = return address), raw members load at 0x0100.
"""

from cvit.src.fsload import (NAME, NLEN, PATH, PLEN, PSTART, SLASH,
                             PFX, DSEC, USEC, LIBP, DBYTES, ROW, RPTR,
                             DIDX, RCNT, FOUND, PAGE, NEXTP, CAP,
                             TPTR, TEND, SPTR, CNT, NUM, NDIG, GRP, SUB,
                             KEY, BLEN, MCNT, MADD, MRES, TMP, TMP2, CH,
                             CB, PASS, RPAGE, SOFF, SSEC, NSEC, J, BPTR,
                             MATCH, CA, CL, LA, LL, MS, FSERR, STAGE, STAGE_MAX,
                             _inc, _add, _zinc, _yinc, _cmp_char)

WBUF = STAGE + 0x400     # text sector assembly buffer (0x3400)


def emit_fs_save(a):
    # ---------------- parse the SAVE string (BX = string) --------
    a.label("fs_save")
    a.jsr_abs("p_parse_save")
    a.lda_d("p_err").ldb_i(0).sab().bnz("w_savewhat")
    a.lda_d(PFX).ldb_i(2).sab().bz("w_nolib")
    a.jmp_abs("w_lib")
    a.label("w_lib")
    a.jsr_abs("fs_libset")
    # ---------------- main flow ----------------
    a.label("w_main")
    a.jsr_abs("w_count")
    a.lda_i(0xFFFF).sta_d(NSEC)
    a.lda_i(0).sta_d(FOUND)
    a.lda_i(1).sta_d(PASS)
    a.jsr_abs("fs_scan")
    a.lda_d(SSEC).sta_d("w_rowsec")
    a.lda_d(SOFF).sta_d("w_rowoff")
    a.lda_d(NSEC).sta_d("w_termsec")
    a.lda_d(BPTR).sta_d("w_termoff")
    a.lda_d(FOUND).ldb_i(0).sab().bnz("w_found")
    a.jmp_abs("w_create")
    a.label("w_found")
    a.lda_d(LIBP).sta_d(NEXTP)
    a.lda_i(2).sta_d(PASS)
    a.jsr_abs("fs_scan")
    a.lda_d(NEXTP).ldb_d(PAGE).sab().stb_d(MCNT)
    a.lda_i(200).sta_d(MADD)
    a.jsr_abs("fs_mul")
    a.lda_d(MRES).sta_d(CAP)
    a.lda_d("w_tlen").ldb_d(CAP).sab().bz("w_write")
    a.lda_d("w_tlen").ldb_d(CAP).sab().bnc("w_write")
    a.jsr_abs("w_ceil400")
    a.jsr_abs("w_alloc")
    a.lda_d("w_ok").ldb_i(0).sab().bz("w_toobig")
    a.jsr_abs("w_patchrow")
    a.lda_d("w_newpage").sta_d(PAGE)
    a.lda_d("w_sectors").sta_d(MCNT)
    a.lda_i(400).sta_d(MADD)
    a.jsr_abs("fs_mul")
    a.lda_d(MRES).sta_d(CAP)
    a.jmp_abs("w_write")
    a.label("w_create")
    a.lda_d("w_termsec").ldb_i(0xFFFF).sab().bnz("w_cr_have")
    a.jmp_abs("w_crfail")
    a.label("w_cr_have")
    a.lda_d("w_termsec").sta_d(MCNT)
    a.lda_i(400).sta_d(MADD)
    a.jsr_abs("fs_mul")
    a.lda_d(MRES).ldb_d("w_termoff").aab().stb_d(TMP)
    _add(a, TMP, 16)
    a.lda_d(TMP).ldb_d(DBYTES).sab().bz("w_crfail")
    a.lda_d(TMP).ldb_d(DBYTES).sab().bl("w_crfail")
    a.jsr_abs("w_ceil400")
    a.jsr_abs("w_alloc")
    a.lda_d("w_ok").ldb_i(0).sab().bz("w_crfail")
    a.jsr_abs("w_writerow")
    a.lda_d("w_newpage").sta_d(PAGE)
    a.lda_d("w_sectors").sta_d(MCNT)
    a.lda_i(400).sta_d(MADD)
    a.jsr_abs("fs_mul")
    a.lda_d(MRES).sta_d(CAP)
    a.jmp_abs("w_write")
    a.label("w_crfail")
    a.lda_d("w_tlen").ldb_i(400).sab().bz("w_crnofile")
    a.lda_d("w_tlen").ldb_i(400).sab().bl("w_toobig")
    a.label("w_crnofile")
    a.jmp_abs("fs_nofile")
    # ---------------- count pass: TLEN and NSLOTS ----------------
    a.label("w_div100")
    a.lda_d(KEY).sta_d(SUB)
    a.lda_i(0).sta_d(GRP)
    a.label("w_d100_l")
    a.lda_d(SUB).ldb_i(100).sab().bnc("w_d100_done")
    a.lda_d(SUB).ldb_i(100).sab().stb_d(SUB)
    _inc(a, GRP)
    a.jmp_abs("w_d100_l")
    a.label("w_d100_done")
    a.rsr()
    a.label("w_count")
    a.lda_i(0).sta_d("w_nslots")
    a.lda_i(0).sta_d("w_tlen")
    a.lda_i(0x8000).sta_d(SPTR)
    a.lda_i(128).sta_d(CNT)
    a.label("w_cnt_l")
    a.lda_d(CNT).ldb_i(0).sab().bz("w_cnt_done")
    a.lda_d(SPTR).xaz().lda_z(0).sta_d(KEY)
    a.lda_d(KEY).ldb_i(0).sab().bz("w_cnt_next")
    _inc(a, "w_nslots")
    a.jsr_abs("w_div100")
    a.lda_d(SPTR).ldb_i(2).aab().xfr("B", "Z")
    a.lda_i(0).sta_d(BLEN)
    a.label("w_cnt_bl")
    a.lda_d(BLEN).ldb_i(62).sab().bz("w_cnt_bd")
    a.lda_i(0).ldab_z(0).stab_d(CH)
    a.lda_i(0).ldab_d(CH).ldbb_i(0).sabb().bz("w_cnt_bd")
    a.lda_i(0).ldab_d(CH).ldbb_i(0x0D).sabb().bz("w_cnt_bd")
    _inc(a, BLEN)
    _zinc(a)
    a.jmp_abs("w_cnt_bl")
    a.label("w_cnt_bd")
    a.lda_d(GRP).ldb_i(10).sab().bnc("w_cnt_d1")
    a.lda_i(2).sta_d(TMP)
    a.jmp_abs("w_cnt_dd")
    a.label("w_cnt_d1")
    a.lda_i(1).sta_d(TMP)
    a.label("w_cnt_dd")
    a.lda_d(BLEN).ldb_d(TMP).aab().stb_d(TMP)
    _add(a, TMP, 6)
    a.lda_d("w_tlen").ldb_d(TMP).aab().stb_d("w_tlen")
    a.label("w_cnt_next")
    _add(a, SPTR, 64)
    a.lda_d(CNT).ldb_i(1).sab().stb_d(CNT)
    a.jmp_abs("w_cnt_l")
    a.label("w_cnt_done")
    a.rsr()
    # ---------------- extent allocation ----------------
    a.label("w_ceil400")
    a.lda_i(0).sta_d("w_sectors")
    a.lda_d("w_tlen").sta_d(TMP)
    a.label("w_c4_l")
    a.lda_d(TMP).ldb_i(0).sab().bz("w_c4_done")
    a.lda_d(TMP).ldb_i(400).sab().bnc("w_c4_tail")
    a.lda_d(TMP).ldb_i(400).sab().stb_d(TMP)
    _inc(a, "w_sectors")
    a.jmp_abs("w_c4_l")
    a.label("w_c4_tail")
    _inc(a, "w_sectors")
    a.label("w_c4_done")
    a.lda_d("w_sectors").ldb_i(0).sab().bnz("w_c4_r")
    a.lda_i(1).sta_d("w_sectors")
    a.label("w_c4_r")
    a.rsr()
    a.label("w_alloc")
    a.lda_i(0).sta_d("w_ok")
    a.lda_d(USEC).sta_d(CB)
    a.lda_i(STAGE).sta_d(CB + 2)
    a.jsr_abs("w_rsec")
    a.lda_d(STAGE).ldb_i(1).aab().stb_d("w_nsec")
    a.lda_d(DSEC).ldb_d("w_nsec").aab().stb_d("w_newsec")
    a.lda_d(PFX).ldb_i(0).sab().bnz("w_al_nolim")
    a.lda_d("w_newsec").ldb_d("w_sectors").aab().stb_d(TMP)
    a.lda_d(TMP).ldb_i(0x100).sab().bz("w_al_nolim")
    a.lda_d(TMP).ldb_i(0x100).sab().bl("w_al_r")
    a.label("w_al_nolim")
    a.lda_i(0).sta_d("w_i")
    a.label("w_al_l")
    a.lda_d("w_i").ldb_d("w_sectors").sab().bl("w_al_word")
    a.lda_i(WBUF).xfr("A", "Y")
    a.lda_i(0).sta_d("w_j")
    a.label("w_al_fl")
    a.lda_d("w_j").ldb_i(400).sab().bz("w_al_fw")
    a.ldbb_i(0x20).xfrb_bl_al().stab_x("Y", disp=0)
    _yinc(a)
    _inc(a, "w_j")
    a.jmp_abs("w_al_fl")
    a.label("w_al_fw")
    a.lda_d("w_newsec").ldb_d("w_i").aab().stb_d(CB)
    a.lda_i(WBUF).sta_d(CB + 2)
    a.jsr_abs("w_wsec")
    a.lda_d("w_newsec").ldb_d("w_i").aab().stb_d("w_sectmp")
    a.jsr_abs("w_appendual")
    _inc(a, "w_i")
    a.jmp_abs("w_al_l")
    a.label("w_al_word")
    a.lda_d(USEC).sta_d(CB)
    a.lda_i(STAGE).sta_d(CB + 2)
    a.jsr_abs("w_rsec")
    a.lda_d("w_nsec").ldb_d("w_sectors").aab().stb_d(TMP)
    a.lda_d(TMP).ldb_i(1).sab().stb_d(TMP)
    a.lda_d(TMP).sta_d(STAGE)
    a.lda_d(USEC).sta_d(CB)
    a.lda_i(STAGE).sta_d(CB + 2)
    a.jsr_abs("w_wsec")
    a.lda_d("w_nsec").sta_d(MADD)
    a.lda_i(2).sta_d(MCNT)
    a.jsr_abs("fs_mul")
    a.lda_d(MRES).sta_d("w_newpage")
    a.lda_i(1).sta_d("w_ok")
    a.label("w_al_r")
    a.rsr()
    a.label("w_appendual")
    a.lda_i(0).sta_d("w_us")
    a.label("w_au_l")
    a.lda_d("w_us").ldb_i(6).sab().bl("w_au_r")
    a.lda_d(USEC).ldb_d("w_us").aab().stb_d(CB)
    a.lda_i(STAGE).sta_d(CB + 2)
    a.jsr_abs("w_rsec")
    a.lda_d("w_us").ldb_i(0).sab().bnz("w_au_p0")
    a.lda_i(6).sta_d("w_p")
    a.jmp_abs("w_au_pl")
    a.label("w_au_p0")
    a.lda_i(0).sta_d("w_p")
    a.label("w_au_pl")
    a.lda_d("w_p").ldb_i(398).sab().bl("w_au_next")
    a.lda_d("w_p").ldb_i(STAGE).aab().xfr("B", "Y")
    a.lda_i(0).ldab_x("Y", disp=0).ldbb_i(0xFF).sabb().bnz("w_au_np")
    a.lda_i(0).ldab_x("Y", disp=1).ldbb_i(0xFF).sabb().bnz("w_au_np")
    a.lda_i(0).ldab_x("Y", disp=2).ldbb_i(0xFF).sabb().bnz("w_au_np")
    a.lda_i(0).stab_x("Y", disp=0)
    a.lda_d("w_sectmp").xfrb_au_al().stab_x("Y", disp=1)
    a.lda_d("w_sectmp").stab_x("Y", disp=2)
    a.lda_d("w_p").ldb_i(5).aab().stb_d(TMP)
    a.lda_d(TMP).ldb_i(400).sab().bnc("w_au_wr")
    a.jmp_abs("w_au_wr2")
    a.label("w_au_wr")
    a.ldbb_i(0xFF).xfrb_bl_al().stab_x("Y", disp=3)
    a.ldbb_i(0xFF).xfrb_bl_al().stab_x("Y", disp=4)
    a.ldbb_i(0xFF).xfrb_bl_al().stab_x("Y", disp=5)
    a.label("w_au_wr2")
    a.lda_d(USEC).ldb_d("w_us").aab().stb_d(CB)
    a.lda_i(STAGE).sta_d(CB + 2)
    a.jsr_abs("w_wsec")
    a.rsr()
    a.label("w_au_np")
    _add(a, "w_p", 3)
    a.jmp_abs("w_au_pl")
    a.label("w_au_next")
    _inc(a, "w_us")
    a.jmp_abs("w_au_l")
    a.label("w_au_r")
    a.rsr()
    # ---------------- directory row writes ----------------
    a.label("w_pageparts")
    a.lda_d("w_newpage").sta_d(TMP)
    a.lda_i(0).sta_d("w_pghi")
    a.label("w_pp_l")
    a.lda_d(TMP).ldb_i(128).sab().bnc("w_pp_done")
    a.lda_d(TMP).ldb_i(128).sab().stb_d(TMP)
    _inc(a, "w_pghi")
    a.jmp_abs("w_pp_l")
    a.label("w_pp_done")
    a.lda_d(TMP).sta_d("w_pglo")
    _add(a, "w_pghi", 8)
    a.rsr()
    a.label("w_patchrow")
    a.jsr_abs("w_pageparts")
    a.lda_d(DSEC).ldb_d("w_rowsec").aab().stb_d(CB)
    a.lda_i(STAGE).sta_d(CB + 2)
    a.jsr_abs("w_rsec")
    a.lda_d("w_rowoff").ldb_i(STAGE).aab().xfr("B", "Y")
    a.lda_d("w_pglo").stab_x("Y", disp=10)
    a.lda_d("w_pghi").stab_x("Y", disp=12)
    a.lda_d(DSEC).ldb_d("w_rowsec").aab().stb_d(CB)
    a.lda_i(STAGE).sta_d(CB + 2)
    a.jsr_abs("w_wsec")
    a.rsr()
    a.label("w_writerow")
    a.jsr_abs("w_pageparts")
    a.lda_d(DSEC).ldb_d("w_termsec").aab().stb_d(CB)
    a.lda_i(STAGE).sta_d(CB + 2)
    a.jsr_abs("w_rsec")
    a.lda_d("w_termoff").ldb_i(STAGE).aab().xfr("B", "Y")
    a.lda_i(0).sta_d("w_i")
    a.label("w_wr_nl")
    a.lda_d("w_i").ldb_i(10).sab().bz("w_wr_rest")
    a.lda_d("w_i").ldb_d(NLEN).sab().bnc("w_wr_ch")
    a.ldbb_i(0xA0).xfrb_bl_al().stab_x("Y", disp=0)
    a.jmp_abs("w_wr_nx")
    a.label("w_wr_ch")
    a.lda_d("w_i").ldb_i(NAME).aab().xfr("B", "Z")
    a.lda_i(0).ldab_z(0)
    a.ldb_i(0x80).aab().xfrb_bl_al().stab_x("Y", disp=0)
    a.label("w_wr_nx")
    _yinc(a)
    _inc(a, "w_i")
    a.jmp_abs("w_wr_nl")
    a.label("w_wr_rest")
    a.lda_d("w_pglo").stab_x("Y", disp=0)
    a.lda_i(0).stab_x("Y", disp=1)
    a.lda_d("w_pghi").stab_x("Y", disp=2)
    a.ldbb_i(0x04).xfrb_bl_al().stab_x("Y", disp=3)
    a.lda_i(0).stab_x("Y", disp=4)
    a.lda_i(0).stab_x("Y", disp=5)
    a.lda_d("w_termoff").ldb_i(16).aab().stb_d(TMP)
    a.lda_d(TMP).ldb_i(400).sab().bnc("w_wr_tsame")
    a.lda_d(DSEC).ldb_d("w_termsec").aab().stb_d(CB)
    a.lda_i(STAGE).sta_d(CB + 2)
    a.jsr_abs("w_wsec")
    a.lda_d(DSEC).ldb_d("w_termsec").aab().stb_d(CB)
    _inc(a, CB)
    a.lda_i(STAGE).sta_d(CB + 2)
    a.jsr_abs("w_rsec")
    a.ldbb_i(0x84).xfrb_bl_al().stab_d(STAGE)
    a.ldbb_i(0x8D).xfrb_bl_al().stab_d(STAGE + 1)
    a.lda_d(DSEC).ldb_d("w_termsec").aab().stb_d(CB)
    _inc(a, CB)
    a.lda_i(STAGE).sta_d(CB + 2)
    a.jsr_abs("w_wsec")
    a.rsr()
    a.label("w_wr_tsame")
    a.lda_d("w_termoff").ldb_i(STAGE).aab().xfr("B", "Y")
    a.ldbb_i(0x84).xfrb_bl_al().stab_x("Y", disp=16)
    a.ldbb_i(0x8D).xfrb_bl_al().stab_x("Y", disp=17)
    a.lda_d(DSEC).ldb_d("w_termsec").aab().stb_d(CB)
    a.lda_i(STAGE).sta_d(CB + 2)
    a.jsr_abs("w_wsec")
    a.rsr()
    # ---------------- serializer and sector writer ----------------
    a.label("w_write")
    a.lda_i(0).sta_d("w_woff")
    a.lda_i(0).sta_d("w_emit")
    a.lda_i(0).sta_d("w_lastk")
    a.lda_i(0).sta_d("w_lasts")
    a.lda_d(PAGE).sta_d(TMP)
    a.lda_d(DSEC).sta_d("w_cursec")
    a.label("w_w_p2")
    a.lda_d(TMP).ldb_i(2).sab().bnc("w_w_p2d")
    a.lda_d(TMP).ldb_i(2).sab().stb_d(TMP)
    _inc(a, "w_cursec")
    a.jmp_abs("w_w_p2")
    a.label("w_w_p2d")
    a.lda_d(TMP).ldb_i(0).sab().bnz("w_w_odd")
    a.lda_i(0).sta_d("w_base")
    a.jmp_abs("w_w_begin")
    a.label("w_w_odd")
    a.lda_i(0).ldb_i(200).sab().stb_d("w_base")
    a.label("w_w_begin")
    a.jsr_abs("w_bsec")
    a.label("w_w_loop")
    a.lda_d("w_emit").ldb_d("w_nslots").sab().bz("w_w_flush")
    a.lda_i(0xFFFF).sta_d("w_bkey")
    a.lda_i(0).sta_d("w_bslot")
    a.lda_i(0x8000).sta_d(SPTR)
    a.lda_i(128).sta_d(CNT)
    a.label("w_w_sl")
    a.lda_d(CNT).ldb_i(0).sab().bz("w_w_got")
    a.lda_d(SPTR).xaz().lda_z(0).sta_d(KEY)
    a.lda_d(KEY).ldb_i(0).sab().bz("w_w_snx")
    a.lda_d(KEY).ldb_d("w_lastk").sab().bnc("w_w_snx")
    a.lda_d(KEY).ldb_d("w_lastk").sab().bnz("w_w_cand")
    a.lda_d(SPTR).ldb_d("w_lasts").sab().bz("w_w_snx")
    a.lda_d(SPTR).ldb_d("w_lasts").sab().bnc("w_w_snx")
    a.label("w_w_cand")
    a.lda_d(KEY).ldb_d("w_bkey").sab().bnc("w_w_set")
    a.lda_d(KEY).ldb_d("w_bkey").sab().bnz("w_w_snx")
    a.lda_d(SPTR).ldb_d("w_bslot").sab().bnc("w_w_set")
    a.jmp_abs("w_w_snx")
    a.label("w_w_set")
    a.lda_d(KEY).sta_d("w_bkey")
    a.lda_d(SPTR).sta_d("w_bslot")
    a.label("w_w_snx")
    _add(a, SPTR, 64)
    a.lda_d(CNT).ldb_i(1).sab().stb_d(CNT)
    a.jmp_abs("w_w_sl")
    a.label("w_w_got")
    a.lda_d("w_bkey").sta_d(KEY)
    a.jsr_abs("w_div100")
    a.lda_d(GRP).ldb_i(10).sab().bnc("w_w_g1")
    a.lda_d(GRP).sta_d(TMP)
    a.lda_i(0).sta_d("w_i")
    a.label("w_w_gt")
    a.lda_d(TMP).ldb_i(10).sab().bnc("w_w_gtd")
    a.lda_d(TMP).ldb_i(10).sab().stb_d(TMP)
    _inc(a, "w_i")
    a.jmp_abs("w_w_gt")
    a.label("w_w_gtd")
    a.lda_d("w_i").ldb_i(0x30).aab().stb_d("w_ch")
    a.jsr_abs("w_putc")
    a.lda_d(TMP).ldb_i(0x30).aab().stb_d("w_ch")
    a.jsr_abs("w_putc")
    a.jmp_abs("w_w_dot")
    a.label("w_w_g1")
    a.lda_d(GRP).ldb_i(0x30).aab().stb_d("w_ch")
    a.jsr_abs("w_putc")
