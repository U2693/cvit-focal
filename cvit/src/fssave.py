    a.lda_d(J).sta_d(SLASH)
    a.label("p_sl_done")
    # ---------------- member name ----------------
    a.lda_d(SLASH).ldb_i(0xFFFF).sab().bnz("p_ms_slash")
    a.lda_d(PSTART).sta_d(MS)
    a.jmp_abs("p_ms_have")
    a.label("p_ms_slash")
    a.lda_d(SLASH).ldb_i(1).aab().stb_d(MS)
    a.label("p_ms_have")
    a.lda_d(PLEN).ldb_d(MS).sab().stb_d(TMP)
    a.lda_d(TMP).ldb_i(0).sab().bz("p_empty")
