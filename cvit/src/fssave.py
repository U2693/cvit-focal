    a.lda_i(PATH).sta_d(CA)
    a.lda_d("p_w1p").sta_d(LA)
    a.lda_d("p_w1l").sta_d(LL)
    a.lda_d("p_w1l").sta_d(CL)
    a.lda_d(PLEN).ldb_d("p_w1l").sab().bnc("p_try2")
    a.jsr_abs("fs_cmplit")
    a.lda_d(MATCH).ldb_i(0).sab().bz("p_try2")
    a.lda_d("p_w1l").sta_d(PSTART)
    a.jmp_abs("p_dev")
    a.label("p_try2")
    a.lda_i(PATH).sta_d(CA)
    a.lda_d("p_w2p").sta_d(LA)
    a.lda_d("p_w2l").sta_d(LL)
    a.lda_d("p_w2l").sta_d(CL)
    a.lda_d(PLEN).ldb_d("p_w2l").sab().bnc("p_dev")
    a.jsr_abs("fs_cmplit")
    a.lda_d(MATCH).ldb_i(0).sab().bz("p_dev")
    a.lda_d("p_w2l").sta_d(PSTART)
    # ---------------- device prefix ----------------
    a.label("p_dev")
    a.lda_i(0).sta_d("p_devn")
    a.lda_d(PSTART).ldb_i(PATH).aab().xfr("B", "Z")
